package edu.carroll.cs341.service;

import edu.carroll.cs341.jpa.model.Family;
import edu.carroll.cs341.jpa.model.Game;
import edu.carroll.cs341.jpa.model.GameOwned;
import edu.carroll.cs341.jpa.model.User;

import java.util.List;

/**
 * Defines the service operations for managing games owned by users.
 *
 * <p>This interface provides methods for retrieving a user's game collection,
 * adding games to that collection, removing games from a collection, and
 * retrieving games owned by a family.</p>
 *
 * <p>Implementations are responsible for handling the business logic involved
 * in associating games with users and retrieving or removing ownership records.</p>
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT assisted with reviewing and updating Javadoc comments
 *   in conjunction with Max Montowski. All comments were reviewed by
 *   the author. No code was generated by ChatGPT.</li>
 * </ul>
 */
public interface GamesOwnedService {

    /**
     * Retrieves all game ownership records associated with a user.
     *
     * @param user the user whose owned games are being retrieved
     * @return a list of games owned by the specified user
     */
    List<GameOwned> getGamesOwnedByUsername(User user);

    /**
     * Adds a game to the specified user's collection.
     *
     * @param user         the user adding the game
     * @param gameID       the ID of the game to add
     * @param yearProduced the year the owned game was produced
     * @return {@code true} if the game was added successfully;
     * {@code false} otherwise
     */
    boolean addGameToCollection(User user, Long gameID, Integer yearProduced);

    /**
     * Removes a game ownership record from a user's collection.
     *
     * @param user        the user requesting the removal
     * @param gameOwnedID the ID of the game ownership record to remove
     * @return {@code true} if the game was removed successfully;
     * {@code false} otherwise
     */
    boolean removeGameFromCollection(User user, Long gameOwnedID);

    /**
     * Retrieves the game ownership records associated with a family.
     *
     * @param family the family whose owned games are being retrieved
     * @return a list of games owned by members of the specified family
     */
    List<GameOwned> getGamesOwnedByFamily(Family family);

    /**
     * Retrieves the number of ownership records referencing a specific game
     * for a user.
     *
     * @param gameID the ID of the game whose references are being counted
     * @param user   the user whose game references are being counted
     * @return the number of ownership records referencing the specified game
     */
    long getNumberOfReferences(Long gameID, User user);

    /**
     * Updates the game references associated with a user's collection.
     *
     * @param gameID the ID of the game whose references are being updated
     * @param user   the user whose game references are being updated
     * @param newGame the new game to associate with the ownership records
     * @return {@code true} if the game references were updated successfully;
     * {@code false} otherwise
     */
    boolean updateGameReferences(Long gameID, User user, Game newGame);

    /**
     * Edits a game ownership record in a user's collection.
     *
     * @param user         the user whose collection contains the game
     * @param gameOwnedID  the ID of the game ownership record to edit
     * @param game         the updated game information
     * @param yearProduced the updated year the game was produced
     * @return {@code true} if the ownership record was updated successfully;
     * {@code false} otherwise
     */
    boolean editGameInCollection(User user, Long gameOwnedID, Game game, Integer yearProduced);

    /**
     * Retrieves a specific game ownership record belonging to a user.
     *
     * @param user        the user whose collection is being searched
     * @param gameOwnedID the ID of the game ownership record to retrieve
     * @return the matching game ownership record, or {@code null} if no
     * matching record is found
     */
    GameOwned getGameOwnedByID(User user, Long gameOwnedID);

}
