package edu.carroll.cs341.service;

import edu.carroll.cs341.jpa.model.GameOwned;

import java.util.List;

/**
 * Defines the service operations for managing games owned by users.
 * This interface provides methods for retrieving a user's game collection
 * and adding games to that collection.
 *
 * Implementations are responsible for handling the business logic involved
 * in associating games with users and retrieving their ownership records.
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author. No code was generated by ChatGPT.</li>
 * </ul>
 */
public interface GamesOwnedService {

    /**
     * Retrieves all game ownership records associated with a username.
     *
     * @param username the username whose owned games are being retrieved
     * @return a list of games owned by the specified user
     */
    List<GameOwned> getGamesOwnedByUsername(String username);

    /**
     * Adds a game to the specified user's collection.
     *
     * @param username the username of the user adding the game
     * @param gameID the ID of the game to add
     * @param yearProduced the year the owned game was produced
     */
    void addGame(String username, Long gameID, Integer yearProduced);
}
