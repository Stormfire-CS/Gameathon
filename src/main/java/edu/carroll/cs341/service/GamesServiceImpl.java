package edu.carroll.cs341.service;

import edu.carroll.cs341.jpa.model.Game;
import edu.carroll.cs341.jpa.model.User;
import edu.carroll.cs341.jpa.repo.GamesRepository;
import edu.carroll.cs341.jpa.repo.UserRepository;
import jakarta.transaction.Transactional;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;

import java.util.Comparator;
import java.util.HashMap;
import java.util.LinkedList;
import java.util.List;
import java.util.Map;

/**
 * Implements the service operations for managing games in the game catalog.
 * This class retrieves games available to users and allows users to add
 * new games to the catalog.
 * <p>
 * Games added by users are associated with the account of the person who
 * added them. The service uses repositories to retrieve user and game
 * information and to save new game records.
 * </p>
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>Robin. "Merging two Maps." Stack Overflow, January 9, 2012.
 *   Used as a reference for combining map entries.
 *   https://stackoverflow.com/questions/8795945/merging-two-maps</li>
 *
 *   <li>ChatGPT assisted with reviewing and updating Javadoc comments
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author.
 *   No code was generated by ChatGPT.</li>
 * </ul>
 */
@Service
public class GamesServiceImpl implements GamesService {

    /**
     * Logger used to record service activity and debugging information.
     */
    private static final Logger log = LoggerFactory.getLogger(GamesServiceImpl.class);

    /**
     * Repository for retrieving and saving game catalog records.
     */
    private final GamesRepository gamesRepo;

    /**
     * Service for managing games owned by users.
     */
    private final GamesOwnedService gamesOwnedService;

    /**
     * Constructs the service with the repositories needed to manage games
     * and identify the users who add them.
     *
     * @param gamesRepo repository for game catalog operations
     */
    public GamesServiceImpl(GamesRepository gamesRepo, GamesOwnedService gamesOwnedService) {
        this.gamesRepo = gamesRepo;
        this.gamesOwnedService = gamesOwnedService;
    }

    /**
     * Retrieves the games available to a specified owner.
     * The results include games available to all users and games added
     * by the specified owner, sorted alphabetically by game name.
     *
     * @param user the ID of the owner whose available games are requested
     * @return a list of available games sorted by name
     */
    @Override
    public List<Game> getAvailableGames(User user) {
        log.info("getAvailableGames: getting games for the owner '{}'", user);

        // Ensure user is not null
        if (user == null) {
            log.error("getAvailableGames: user was null");
            return new LinkedList<>();
        }

        // Retrieve globally available games along with those added by this owner.
        List<Game> games = gamesRepo.findByUserWhoAddedIsNullOrUserWhoAddedOrderByGameNameAsc(user);

        /*
         * Source:
         * Robin. "Merging two Maps." Stack Overflow, January 9, 2012.
         * https://stackoverflow.com/questions/8795945/merging-two-maps
         *
         * The approach of iterating through map entries and adding entries
         * only when their keys are not already present was used as a
         * reference for combining the two maps below.
         */

        // The two maps to be combined
        Map<String, Game> defaultGames = new HashMap<>();
        Map<String, Game> userGames = new HashMap<>();

        // Splits the games into default and user-added games
        for (Game game : games) {
            String gameName = game.getGameName();

            if (game.getUserWhoAdded() == null) {
                defaultGames.put(gameName, game);
            } else {
                userGames.put(gameName, game);
            }
        }

        // Combines the two maps
        for (Map.Entry<String, Game> game : defaultGames.entrySet()) {
            userGames.computeIfAbsent(game.getKey(), k -> game.getValue());
        }

        // Removes games that the user cannot see
        userGames.entrySet().removeIf(game -> !game.getValue().getCanSee());

        // Creates a list of available games and sorts it
        List<Game> availableGames = new LinkedList<>(userGames.values());
        availableGames.sort(Comparator.comparing(Game::getGameName, String.CASE_INSENSITIVE_ORDER));
        log.debug("getAvailableGames: found {} available games", availableGames.size());
        return availableGames;
    }

    /**
     * Adds a new game to the catalog and associates it with the user
     * who submitted it.
     * The operation stops if the username does not identify exactly one
     * user or if a game with the same name already exists.
     *
     * @param user       the username of the person adding the game
     * @param gameName   the name of the game to add
     * @param minPlayers the minimum number of players supported by the game
     * @param maxPlayers the maximum number of players supported by the game
     */
    @Transactional
    @Override
    public boolean addGame(User user, String gameName, Integer minPlayers, Integer maxPlayers) {
        log.debug("addGame: '{}' attempted to add game: {}", user, gameName);

        // Ensures the user is not null
        if (user == null) {
            log.error("addGame: user was null");
            return false;
        }

        // Ensures the game name is not null
        if (gameName == null) {
            log.error("addGame: game name was null");
            return false;
        }

        // Ensures the game name is not empty
        gameName = gameName.trim();
        if (gameName.isEmpty()) {
            log.warn("game name is empty");
            return false;
        }

        // Ensures the max players is not less than the min players
        if (maxPlayers != null && minPlayers != null) {
            if (maxPlayers < minPlayers) {
                log.error("addGame: max players {} was less than min players {}", maxPlayers, minPlayers);
                return false;
            }
        }

        // Ensures the max players and min players are not less than zero
        if ((maxPlayers != null && maxPlayers < 0) || (minPlayers != null && minPlayers < 0)) {
            log.error("addGame: max player {} or min player {} was less than zero", maxPlayers, minPlayers);
            return false;
        }

        // Check whether the user already owns a game with this name.
        Game existingGame = gamesRepo.findByGameNameIgnoreCaseAndUserWhoAdded(gameName, user);
        if (existingGame != null) {
            // Do not allow adding a game that is already visible.
            if (existingGame.getCanSee()) {
                log.debug("addGame: user {} already has a visible game named {}", user.getUsername(), gameName);
                return false;
            }

            // Update the existing hidden game and make it visible.
            existingGame.setMaxPlayers(maxPlayers);
            existingGame.setMinPlayers(minPlayers);
            existingGame.setCanSee(true);
            gamesRepo.save(existingGame);

            log.info("addGame: {} restored game {}", user, gameName);
            return true;
        }

        // Check whether a default game with this name already exists.
        Game defaultGame = gamesRepo.findByGameNameIgnoreCaseAndUserWhoAddedIsNull(gameName);
        if (defaultGame != null) {
            log.debug("addGame: default game {} already exists", gameName);
            return false;
        }

        // Create the new game record after confirming the name is not already used.
        Game newGame = new Game(gameName);

        // Store the supported player range and the ID of the user who added the game.
        newGame.setMaxPlayers(maxPlayers);
        newGame.setMinPlayers(minPlayers);
        newGame.setUserWhoAdded(user);
        newGame.setCanSee(true);

        // Save the new game to the catalog.
        gamesRepo.save(newGame);
        log.info("addGame: {} added {}", user, newGame);
        return true;
    }

    /**
     * Edits the specified game with the provided details.
     *
     * @param user       the user attempting to edit the game
     * @param gameID     the ID of the game to edit
     * @param gameName   the updated name of the game
     * @param minPlayers the updated minimum number of players
     * @param maxPlayers the updated maximum number of players
     * @return {@code true} if the game was successfully edited;
     * {@code false} otherwise
     */
    @Transactional
    @Override
    public boolean editGame(User user, Long gameID, String gameName,
                            Integer minPlayers, Integer maxPlayers) {
        log.debug("editGame: {} attempting to edit game {}", user, gameID);

        // Tries to retrieve the game by its ID
        Game game = getGameByGameID(gameID);

        // Ensures user is not null
        if (user == null) {
            log.warn("editGame: null user");
            return false;
        }

        // Ensures game is not null
        if (game == null) {
            log.error("editGame: null Game");
            return false;
        }

        // Ensures gameName is not null
        if (gameName == null) {
            log.error("editGame: null gameName");
            return false;
        }

        // Ensures gameName is not empty
        if (gameName.trim().isEmpty()) {
            log.error("editGame: gameName was empty");
            return false;
        }

        // Ensures max player is not less than min player
        if (maxPlayers != null && minPlayers != null) {
            if (maxPlayers < minPlayers) {
                log.error("editGame: max players {} was less than min players {}", maxPlayers, minPlayers);
                return false;
            }
        }

        // Ensures max and min players are not less than zero
        if ((maxPlayers != null && maxPlayers < 0) || (minPlayers != null && minPlayers < 0)) {
            log.error("editGame: max player {} or min player {} was less than zero", maxPlayers, minPlayers);
            return false;
        }

        // Checks if the user already owns a game with the same name
        String originalName = game.getGameName();
        String newName = gameName.trim();
        Game userCopy = gamesRepo.findByGameNameIgnoreCaseAndUserWhoAdded(originalName, user);

        // The user is keeping the same game name.
        if (originalName.equalsIgnoreCase(newName)) {
            if (userCopy == null) {
                // Create a user-owned copy of the default game.
                userCopy = new Game();
                userCopy.setUserWhoAdded(user);
            }

            // Sets the game name, min players, and max players
            userCopy.setGameName(newName);
            userCopy.setMinPlayers(minPlayers);
            userCopy.setMaxPlayers(maxPlayers);
            userCopy.setCanSee(true);
            gamesRepo.save(userCopy);
            gamesOwnedService.updateGameReferences(gameID, user, userCopy);
            log.info("editGame: game name changed to '{}'", newName);
            return true;
        }

        // The user is changing the game's name.
        // Check that they do not already have a game with the new name.
        Game existingNewGame = gamesRepo.findByGameNameIgnoreCaseAndUserWhoAdded(
                newName, user);
        Game existingDefaultGame = gamesRepo.findByGameNameIgnoreCaseAndUserWhoAddedIsNull(newName);
        if (existingNewGame != null && existingNewGame.getCanSee()) {
            log.debug("editGame: '{}' already has a game named '{}'", user, newName);
            return false;
        }

        if (existingDefaultGame != null && existingNewGame == null) {
            log.debug("editGame: '{}' already has a game named '{}'", user, newName);
            return false;
        }

        // Checks if the user copy is null
        if (userCopy == null) {
            // Create a hidden copy of the original game to suppress its default.
            userCopy = new Game();
            userCopy.setGameName(originalName);
            userCopy.setMinPlayers(game.getMinPlayers());
            userCopy.setMaxPlayers(game.getMaxPlayers());
            userCopy.setUserWhoAdded(user);
        }

        // Sets the visibility of the user copy to false
        userCopy.setCanSee(false);
        gamesRepo.save(userCopy);

        // Create a new visible game with the updated name and information.
        Game newGame = new Game();
        newGame.setGameName(newName);
        newGame.setMinPlayers(minPlayers);
        newGame.setMaxPlayers(maxPlayers);
        newGame.setUserWhoAdded(user);
        newGame.setCanSee(true);

        // Save the new game to the database
        gamesRepo.save(newGame);
        gamesOwnedService.updateGameReferences(gameID, user, newGame);
        log.info("Game '{}' edited successfully", newName);
        return true;
    }

    /**
     * Removes the specified game from the user's collection.
     *
     * @param user   the user attempting to remove the game
     * @param gameID the ID of the game to remove
     * @return {@code true} if the game was successfully removed;
     * {@code false} otherwise
     */
    @Transactional
    @Override
    public boolean removeGame(User user, Long gameID) {
        log.info("removeGame: '{}' tried to remove the game with the ID {}", user, gameID);
        Game game = getGameByGameID(gameID);

        // Ensure the user is not null
        if (user == null) {
            log.error("removeGame: null user");
            return false;
        }

        // Ensure the game is not null
        if (game == null) {
            log.error("removeGame: null Game");
            return false;
        }

        // Ensure the game is not still referenced by users owned game.
        Long games = gamesOwnedService.getNumberOfReferences(gameID, user);
        if (games != 0) {
            log.debug("removeGame: game is still referenced by users owned game.");
            return false;
        }

        // Creates a new game object associated with the user who removed the game if it is a default game, then
        // sets the game to be invisible.
        if (game.getUserWhoAdded() == null) {
            Game removedGame = new Game();
            removedGame.setGameName(game.getGameName());
            removedGame.setMinPlayers(game.getMinPlayers());
            removedGame.setMaxPlayers(game.getMaxPlayers());
            removedGame.setUserWhoAdded(user);
            removedGame.setCanSee(false);
            gamesRepo.save(removedGame);
            log.debug("removeGame: default {} removed from '{}' collection", game, user);
            return true;
        }

        // Sets the game to be invisible.
        game.setCanSee(false);
        gamesRepo.save(game);
        log.debug("removeGame: '{}' removed from '{}' collection", game, user);
        return true;

    }

    /**
     * Retrieves a game by its ID.
     *
     * @param gameID the ID of the game being requested
     * @return the game with the specified ID, or null if not found
     */
    public Game getGameByGameID(Long gameID) {
        if (gameID == null) {
            log.error("getGameByUserID: gameID is null");
            return null;
        }
        return gamesRepo.findByGameID(gameID);
    }

}
