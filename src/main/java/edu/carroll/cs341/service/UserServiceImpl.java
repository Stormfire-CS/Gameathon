package edu.carroll.cs341.service;

import edu.carroll.cs341.jpa.model.User;
import edu.carroll.cs341.jpa.repo.UserRepository;
import jakarta.transaction.Transactional;
import org.mindrot.jbcrypt.BCrypt;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;

import java.util.List;

/**
 * Implements the service operations for managing user accounts.
 * This class validates login credentials, registers new users, and retrieves
 * user IDs based on usernames.
 *
 * The service uses the login repository to look up and save user account
 * information. It also logs relevant events to assist with debugging
 * and monitoring authentication and registration operations.
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author. No code was generated by ChatGPT.</li>
 * </ul>
 */
@Service
public class UserServiceImpl implements UserService {

    /** Logger used to record authentication and account-management activity. */
    private static final Logger log = LoggerFactory.getLogger(UserServiceImpl.class);

    /** Repository used to look up and save user accounts. */
    private final UserRepository userRepo;

    /**
     * Constructs the service with the repository needed to manage user accounts.
     *
     * @param userRepo repository for retrieving and saving login records
     */
    public UserServiceImpl(UserRepository userRepo) {
        this.userRepo = userRepo;
    }

    /**
     * Determines whether the supplied username and password match an
     * existing user account.
     *
     * @param username the username of the person attempting to log in
     * @param password the password entered by the person attempting to log in
     * @return {@code true} if exactly one matching user exists and the
     * password matches; {@code false} otherwise
     */
    @Override
    public User validateUser(String username, String password) {
        log.debug("validateUser: user '{}' attempted login", username);

        if (username == null || username.isBlank()) {
            log.debug("validateUser: username is blank");
            return null;
        }

        if (password == null || password.isBlank()) {
            log.error("validateUser: password is blank");
            return null;
        }

        // Perform the lookup without distinguishing between uppercase and lowercase usernames.
        List<User> users = userRepo.findByUsernameIgnoreCase(username);

        // Require exactly one matching account to avoid ambiguous authentication results.
        if (users.size() != 1) {
            log.debug("validateUser: found {} users", users.size());
            return null;
        }
        User u = users.getFirst();

        if (!BCrypt.checkpw(password, u.getHashedPassword())) {
            log.debug("validateUser: password !match");
            return null;
        }

        // Authentication succeeds only after the stored and supplied hashes match.
        log.info("validateUser: successful login for {}", u.getUsername());
        return u;
    }

    /**
     * Validates registration information and creates a new user account
     * if the username is available and both passwords match.
     *
     * @param username the username requested for the new account
     * @param password1 the password entered initially
     * @param password2 the password entered for confirmation
     * @return {@code true} if the account was registered successfully;
     * {@code false} if the username already exists or the passwords differ
     */
    @Transactional
    @Override
    public User newUser(String username, String password1, String password2) {
        log.debug("validateNewUser: attempting to register username '{}'", username);

        if (username == null) {
            log.error("validateNewUser: username is null");
            return null;
        }

        if (username.isEmpty()) {
            log.error("validateNewUser: username is blank");
            return null;
        }

        if (password1 == null || password2 == null) {
            log.error("validateNewUser: One or both passwords is null");
            return null;
        }

        if (password1.isEmpty() || password2.isEmpty()) {
            log.error("validateNewUser: One or both passwords is blank");
            return null;
        }

        // Check whether the requested username is already associated with an account.
        List<User> users = userRepo.findByUsernameIgnoreCase(username);
        if (!users.isEmpty()) {
            log.debug("validateNewUser: username '{}' already exists", username);
            return null;
        }

        // Ensure the password confirmation matches before creating the account.
        if (!password1.equals(password2)) {
            log.error("validateNewUser: passwords do not match for '{}'", username);
            return null;
        }

        // Reject usernames containing whitespace.
        if (!username.matches("^\\S+$")) {
            log.error("validateNewUser: username contains whitespace");
            return null;
        }

        // Reject passwords containing whitespace.
        if (!password1.matches("^\\S+$") || !password2.matches("^\\S+$")) {
            log.error("validateNewUser: one or both passwords contain whitespace");
            return null;
        }

        // Construct and save the new login record after validation succeeds.
        User user = new User(username, password1);
        userRepo.save(user);

        log.info("validateNewUser: successfully registered user '{}'", username);
        return user;
    }

    /**
     * Renames the currently selected user's account.
     *
     * @param user the user whose name is being changed
     * @param newName the new name to assign to the user
     * @return true if the user's name was successfully updated; false otherwise
     */
    @Transactional
    @Override
    public Boolean renameUser(User user, String newName) {
        log.debug("renameUser: user {} attempting to change name to '{}'", user, newName);

        if (user == null) {
            log.error("renameUser: user is null");
            return false;
        }

        if (newName == null) {
            log.error("renameUser: newName is null");
            return false;
        }

        if (newName.isEmpty()) {
            log.error("renameUser: newName is empty");
            return false;
        }

        if (newName.length() < 2 || newName.length() > 40) {
            log.error("renameUser: new name must be between 2 and 40 characters");
        }

        // Reject passwords containing whitespace.
        if (!newName.matches("^\\S+$")) {
            log.error("renameUser: new name contains whitespace");
            return false;
        }

        // Update and save the user's name.
        user.setName(newName);
        userRepo.save(user);

        log.info("renameUser: successfully renamed user '{}'", user);
        return true;
    }

    /**
     * Changes the password associated with a user account.
     *
     * @param user the user whose password will be changed
     * @param password the new password to assign to the user
     * @return true if the password was successfully changed; false otherwise
     */
    @Transactional
    @Override
    public Boolean changeUsersPassword(User user, String password) {
        log.debug("changeUsersPassword: user {} attempting to change password", user);

        if (user == null) {
            log.error("changeUsersPassword: user is null");
            return false;
        }

        if (password == null) {
            log.error("changeUsersPassword: password is null");
            return false;
        }

        if (password.isEmpty()) {
            log.error("changeUsersPassword: password is empty");
            return false;
        }

        // Enforce the same password requirements as the form.
        if (password.length() < 8 || password.length() > 30) {
            log.error("changeUsersPassword: password must be between 8 and 30 characters");
            return false;
        }

        // Reject passwords containing whitespace.
        if (!password.matches("^\\S+$")) {
            log.error("changeUsersPassword: password contains whitespace");
            return false;
        }

        // Hash and store the new password.
        user.setRawPassword(password);
        userRepo.save(user);

        log.info("changeUsersPassword: successfully changed password for '{}'", user);
        return true;
    }


}
