package edu.carroll.cs341.service;

import edu.carroll.cs341.jpa.model.User;

/**
 * Defines the service operations for managing user accounts.
 * This interface provides methods for validating login credentials,
 * validating and registering new users, and retrieving user IDs.
 *
 * Implementations are responsible for handling the business logic
 * associated with user authentication, registration, and account lookups.
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author. No code was generated by ChatGPT.</li>
 * </ul>
 */
public interface UserService {

    /**
     * Validates the credentials supplied by a user attempting to log in.
     *
     * @param username the username of the person attempting to log in
     * @param password the password entered by the user
     * @return {@code true} if the credentials are valid; {@code false} otherwise
     */
    User validateUser(String username, String password);

    /**
     * Validates registration information and registers a new user if the
     * username is available and the password confirmation matches.
     *
     * @param username the username requested for the new account
     * @param password1 the password entered initially
     * @param password2 the password entered for confirmation
     * @return {@code true} if registration succeeds; {@code false} otherwise
     */
     User validateNewUser(String username, String password1, String password2);

    /**
     * Retrieves the database ID associated with a username.
     *
     * @param username the username whose ID is requested
     * @return the user's ID if the account can be uniquely identified;
     * {@code null} otherwise
     */
    Long getUserID(String username);
}
