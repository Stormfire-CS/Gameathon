package edu.carroll.cs341.web.controller;

import edu.carroll.cs341.jpa.model.FamilyMembership;
import edu.carroll.cs341.jpa.model.User;
import edu.carroll.cs341.service.FamilyMembershipService;
import edu.carroll.cs341.service.FamilyService;
import edu.carroll.cs341.web.form.FamilyNameForm;
import jakarta.servlet.http.HttpSession;
import jakarta.validation.Valid;
import org.springframework.stereotype.Controller;
import org.springframework.ui.Model;
import org.springframework.validation.BindingResult;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.ModelAttribute;
import org.springframework.web.bind.annotation.PostMapping;

/**
 * Handles web requests for managing family membership and family settings.
 * This controller displays family membership information and pending requests
 * and processes requests to accept, reject, or remove family members.
 * It also handles renaming a family, changing the family administrator, and
 * deleting a family.
 *
 * <p>
 * The controller delegates family-related operations to
 * {@link FamilyService} and {@link FamilyMembershipService} and supplies
 * the information required by the corresponding Thymeleaf views.
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT assisted with reviewing and updating Javadoc comments for this file
 *   in conjunction with Max Montowski. All comments were reviewed by the author.
 *   No code was generated by ChatGPT.</li>
 * </ul>
 */
@Controller
public class EditFamilyController {

    /**
     * Service used to retrieve and manage family information.
     */
    private final FamilyService familyService;

    /**
     * Service used to retrieve and manage family membership requests.
     */
    private final FamilyMembershipService familyMembershipService;

    /**
     * Constructs the controller with the services required to manage
     * family information and family membership.
     *
     * @param familyService service for family-related operations
     * @param familyMembershipService service for family membership operations
     */
    public EditFamilyController(FamilyService familyService, FamilyMembershipService familyMembershipService) {
        this.familyService = familyService;
        this.familyMembershipService = familyMembershipService;
    }

    /**
     * Displays the page containing family membership information and pending requests.
     * Adds the logged-in user, family members, family information, and pending
     * requests to the model for use by the view.
     *
     * @param session the HTTP session containing the logged-in user
     * @param model the model used to supply data to the view
     * @return the family management view, or a redirect to the login page
     * if no user is logged in
     */
    @GetMapping("/editFamilyPage")
    public String addFamilyPage(HttpSession session, Model model) {
        // Ensure the user is logged in, redirect to login page if not.
        User user = (User) session.getAttribute("loggedInUser");
        if (user == null) {
            return "redirect:/login";
        }

        // Makes user and users family members and family available to the view.
        model.addAttribute("user", user);
        model.addAttribute("members", familyMembershipService.getFamilyMembers(user));
        model.addAttribute("family", familyMembershipService.getFamilyForUser(user));

        // Retrieve pending requests so the administrator can review them.
        model.addAttribute("requests", familyMembershipService.getPendingRequests(user));

        // Add family form to the model.
        model.addAttribute("familyNameForm", new FamilyNameForm());
        return "editFamily";
    }

    /**
     * Accepts a pending family membership request and redirects back to
     * the family membership management page.
     *
     * @param session the HTTP session containing the logged-in user
     * @param membershipID the ID of the membership request to accept
     * @return a redirect to the family management page, or a redirect to
     * the family page if the membership record cannot be found
     */
    @PostMapping("/acceptFamilyMember")
    public String acceptFamilyMember(HttpSession session, Long membershipID) {
        // Ensure the user is logged in, redirect to login page if not.
        User user = (User) session.getAttribute("loggedInUser");
        if (user == null) {
            return "redirect:/login";
        }

        // Retrieve the membership record from the service layer.
        FamilyMembership membership = familyMembershipService.getMembershipByID(membershipID);
        if (membership == null) {
            return "redirect:/addFamilyPage";
        }

        // Delegate request validation and acceptance to the service layer.
        familyMembershipService.acceptRequest(user, membership);

        // Return to the request list so it can be refreshed.
        return "redirect:/editFamilyPage";
    }

    /**
     * Rejects a pending family membership request and redirects back to
     * the family membership management page.
     *
     * @param session the HTTP session containing the logged-in user
     * @param membershipID the ID of the membership request to reject
     * @return a redirect to the family management page, or a redirect to
     * the family page if the membership record cannot be found
     */
    @PostMapping("/rejectFamilyMember")
    public String rejectFamilyMember(HttpSession session, Long membershipID) {
        // Ensure the user is logged in, redirect to login page if not.
        User user = (User) session.getAttribute("loggedInUser");
        if (user == null) {
            return "redirect:/login";
        }

        // Retrieve the membership record from the service layer.
        FamilyMembership membership = familyMembershipService.getMembershipByID(membershipID);

        // If the membership record cannot be found, redirect to the family page.
        if (membership == null) {
            return "redirect:/addFamilyPage";
        }

        // Delegate request validation and rejection to the service layer.
        familyMembershipService.rejectRequest(user, membership);

        // Return to the request list so it can be refreshed.
        return "redirect:/editFamilyPage";
    }

    /**
     * Renames the family associated with the logged-in user.
     * Validates the submitted family name before passing the request
     * to the family service.
     *
     * @param session the HTTP session containing the logged-in user
     * @param familyNameForm the form containing the new family name
     * @param bindingResult the result of validating the submitted form
     * @param model the model used to supply data to the view if validation fails
     * @return a redirect to the family management page, the edit family view
     * if validation fails, or a redirect to the login page if no user is logged in
     */
    @PostMapping("/renameFamily")
    public String renameFamily(HttpSession session,
                               @Valid @ModelAttribute("familyNameForm") FamilyNameForm familyNameForm,
                               BindingResult bindingResult,
                               Model model) {
        User user = (User) session.getAttribute("loggedInUser");
        // Ensure the user is logged in, redirect to login page if not.
        if (user == null) {
            return "redirect:/login";
        }

        // If the form has errors, return to the edit family page.
        if (bindingResult.hasErrors()) {
            model.addAttribute("user", user);
            model.addAttribute("members", familyMembershipService.getFamilyMembers(user));
            model.addAttribute("family", familyMembershipService.getFamilyForUser(user));
            model.addAttribute("requests", familyMembershipService.getPendingRequests(user));
            return "editFamily";
        }

        // Rename the family.
        familyService.renameFamily(user, familyNameForm.getFamilyName());
        return "redirect:/editFamilyPage";
    }

    /**
     * Removes a member from the family associated with the logged-in user.
     * Delegates the removal operation to the family membership service.
     *
     * @param session the HTTP session containing the logged-in user
     * @param membershipID the ID of the family membership record to remove
     * @return a redirect to the family management page, or a redirect to
     * the login page if no user is logged in
     */
    @PostMapping("/removeFamilyMember")
    public String removeFamilyMember(HttpSession session, Long membershipID) {
        // Ensure the user is logged in, redirect to login page if not.
        User user = (User) session.getAttribute("loggedInUser");
        if (user == null) {
            return "redirect:/login";
        }

        // Delegate the removal operation to the family membership service.
        familyMembershipService.removeFamilyMember(user, membershipID);
        return "redirect:/editFamilyPage";
    }

    /**
     * Changes the administrator of the family associated with the logged-in user.
     * Retrieves the user associated with the specified membership record and
     * delegates the administrator change to the family service.
     *
     * @param session the HTTP session containing the logged-in user
     * @param membershipID the ID of the membership record belonging to the
     * user who will become the new family administrator
     * @return a redirect to the family page, or a redirect to the login page
     * if no user is logged in
     */
    @PostMapping("/makeFamilyMemberAdmin")
    public String makeFamilyMemberAdmin(HttpSession session, Long membershipID) {
        // Ensure the user is logged in, redirect to login page if not.
        User user = (User) session.getAttribute("loggedInUser");
        if (user == null) {
            return "redirect:/login";
        }

        // Delegate the administrator change operation to the family service.
        familyService.changeAdmin(user, familyMembershipService.getUserByMembershipID(membershipID));
        return "redirect:/familyPage";
    }

    /**
     * Deletes the family associated with the logged-in user.
     * Delegates the deletion operation to the family service.
     *
     * @param session the HTTP session containing the logged-in user
     * @return a redirect to the family page, or a redirect to the login page
     * if no user is logged in
     */
    @PostMapping("/deleteFamily")
    public String deleteFamily(HttpSession session) {
        // Ensure the user is logged in, redirect to login page if not.
        User user = (User) session.getAttribute("loggedInUser");
        if (user == null) {
            return "redirect:/login";
        }

        // Delegate the family deletion operation to the family service.
        familyService.deleteFamily(user);
        return "redirect:/familyPage";
    }
}