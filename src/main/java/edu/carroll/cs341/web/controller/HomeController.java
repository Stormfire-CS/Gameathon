package edu.carroll.cs341.web.controller;

import edu.carroll.cs341.jpa.model.User;
import jakarta.servlet.http.HttpSession;
import org.springframework.stereotype.Controller;
import org.springframework.ui.Model;
import org.springframework.web.bind.annotation.GetMapping;

/**
 * Handles web requests for displaying the application's home page.
 * This controller makes the current username available to the view so
 * the page can display user-specific information or provide navigation
 * to other parts of the application.
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author. No code was generated by ChatGPT.</li>
 * </ul>
 */
@Controller
public class HomeController {

    /**
     * Displays the application's home page.
     * Adds the username to the model so it can be accessed by the view.
     *
     * @param session the username of the user viewing the home page
     * @param model the model used to supply data to the view
     * @return the name of the Thymeleaf view for the home page
     */
    @GetMapping("/homePage")
    public String homePage(HttpSession session, Model model) {

        User user = (User) session.getAttribute("loggedInUser");

        if (user == null) {
            return "redirect:/login";
        }

        // Make the username available to the view for display and navigation.
        model.addAttribute("user", user);

        return "homePage";
    }

}
