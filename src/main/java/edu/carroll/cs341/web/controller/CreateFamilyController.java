package edu.carroll.cs341.web.controller;

import edu.carroll.cs341.jpa.model.User;
import edu.carroll.cs341.service.FamilyService;
import jakarta.servlet.http.HttpSession;
import org.springframework.stereotype.Controller;
import org.springframework.ui.Model;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PostMapping;

/**
 * Handles web requests for creating a new family.
 * This controller displays the family creation page and processes
 * submissions to create a family through the family service.
 * <p>
 * The controller passes the username to the view and delegates family
 * creation and its associated business logic to {@link FamilyService}.
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author. No code was generated by ChatGPT.</li>
 * </ul>
 */
@Controller
public class CreateFamilyController {

    /**
     * Service used to create families and manage family-related operations.
     */
    private final FamilyService familyService;

    /**
     * Constructs the controller with the service required to manage families.
     *
     * @param familyService service for family-related operations
     */
    public CreateFamilyController(FamilyService familyService) {
        this.familyService = familyService;
    }

    /**
     * Displays the page for creating a new family.
     * Makes the username available to the view.
     *
     * @param session the username of the person creating the family
     * @param model   the model used to supply data to the view
     * @return the name of the Thymeleaf view for family creation
     */
    @GetMapping("/createFamilyPage")
    public String createFamilyPage(HttpSession session, Model model) {

        User user = (User) session.getAttribute("loggedInUser");

        if (user == null) {
            return "redirect:/login";
        }

        // Make the username available to the view for use during submission.
        model.addAttribute("user", user);

        return "createFamily";
    }

    /**
     * Processes a submission to create a new family.
     * After delegating the operation to the service, redirects the user
     * to the family page.
     *
     * @param session    the username of the person creating the family
     * @param familyName the name requested for the new family
     * @return a redirect to the family page
     */
    @PostMapping("/createFamily")
    public String createFamily(HttpSession session, String familyName) {

        User user = (User) session.getAttribute("loggedInUser");

        if (user == null) {
            return "redirect:/login";
        }

        // Delegate family creation and validation to the service layer.
        familyService.createFamily(user, familyName);

        // Redirect to the family page after processing the submission.
        return "redirect:/familyPage";
    }
}
