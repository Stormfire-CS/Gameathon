package edu.carroll.cs341.web.controller;

import edu.carroll.cs341.jpa.model.User;
import edu.carroll.cs341.service.FamilyService;
import edu.carroll.cs341.web.form.FamilyNameForm;
import jakarta.servlet.http.HttpSession;
import jakarta.validation.Valid;
import org.springframework.stereotype.Controller;
import org.springframework.ui.Model;
import org.springframework.validation.BindingResult;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.ModelAttribute;
import org.springframework.web.bind.annotation.PostMapping;

/**
 * Handles web requests for creating a new family.
 *
 * <p>This controller displays the family creation page and processes
 * submissions to create a family through the family service.</p>
 *
 * <p>The controller retrieves the logged-in user from the HTTP session
 * and delegates family creation and its associated business logic to
 * {@link FamilyService}.</p>
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT assisted with reviewing and updating Javadoc comments
 *   in conjunction with Max Montowski. All comments were reviewed by
 *   the author. No code was generated by ChatGPT.</li>
 * </ul>
 */
@Controller
public class CreateFamilyController {

    /**
     * Service used to create families and manage family-related operations.
     */
    private final FamilyService familyService;

    /**
     * Constructs the controller with the service required to manage families.
     *
     * @param familyService service for family-related operations
     */
    public CreateFamilyController(FamilyService familyService) {
        this.familyService = familyService;
    }

    /**
     * Displays the page for creating a new family.
     *
     * <p>Checks whether a user is logged in before displaying the page.
     * If no user is logged in, the user is redirected to the login page.
     * Otherwise, the logged-in user and a new family name form are made
     * available to the view.</p>
     *
     * @param session the HTTP session used to retrieve the logged-in user
     * @param model   the model used to provide attributes to the view
     * @return the name of the family creation view, or a redirect to the login page
     */
    @GetMapping("/createFamilyPage")
    public String createFamilyPage(HttpSession session, Model model) {

        // Check if the user is logged in, redirects to the login page if not.
        User user = (User) session.getAttribute("loggedInUser");
        if (user == null) {
            return "redirect:/login";
        }

        // Make the username available to the view for use during submission.
        model.addAttribute("user", user);
        model.addAttribute("familyNameForm", new FamilyNameForm());
        return "createFamily";
    }

    /**
     * Processes a submission to create a new family.
     *
     * <p>Checks whether the user is logged in and validates the submitted
     * family name. If validation fails, the user is returned to the family
     * creation page with the validation errors. Otherwise, the family
     * creation request is delegated to {@link FamilyService}, and the user
     * is redirected to the family page.</p>
     *
     * @param familyNameForm the form containing the requested family name
     * @param result         the object containing validation results and errors
     * @param session        the HTTP session used to retrieve the logged-in user
     * @param model          the model used to provide attributes to the view
     * @return the name of the family creation view if validation fails,
     * or a redirect to the family page after processing
     */
    @PostMapping("/createFamily")
    public String createFamily(@Valid @ModelAttribute FamilyNameForm familyNameForm, BindingResult result, HttpSession session, Model model) {

        // Check if the user is logged in, redirects to the login page if not.
        User user = (User) session.getAttribute("loggedInUser");
        if (user == null) {
            return "redirect:/login";
        }

        // Return to the form if any field-level validation rules fail.
        if (result.hasErrors()) {
            model.addAttribute("user", user);
            return "createFamily";
        }

        // Delegate family creation and validation to the service layer.
        familyService.createFamily(user, familyNameForm.getFamilyName());

        // Redirect to the family page after processing the submission.
        return "redirect:/familyPage";
    }
}
