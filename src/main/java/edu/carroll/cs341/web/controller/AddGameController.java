package edu.carroll.cs341.web.controller;

import edu.carroll.cs341.jpa.model.User;
import edu.carroll.cs341.service.GamesService;
import edu.carroll.cs341.web.form.CreateGameForm;
import jakarta.servlet.http.HttpSession;
import jakarta.validation.Valid;
import org.springframework.stereotype.Controller;
import org.springframework.ui.Model;
import org.springframework.validation.BindingResult;
import org.springframework.validation.ObjectError;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.ModelAttribute;
import org.springframework.web.bind.annotation.PostMapping;

/**
 * Handles web requests for adding new games to the game catalog.
 * This controller displays the page for entering game information and
 * processes submissions to add games through the game service.
 *
 * The controller passes the username to the view and delegates game
 * creation and validation to {@link GamesService}.
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author. No code was generated by ChatGPT.</li>
 * </ul>
 */
@Controller
public class AddGameController {

    /** Service used to add games to the game catalog. */
    private final GamesService gamesService;

    /**
     * Constructs the controller with the service required to manage games.
     *
     * @param gamesService service for retrieving and adding games
     */
    public AddGameController(GamesService gamesService) {
        this.gamesService = gamesService;
    }

    /**
     * Displays the page for adding a new game.
     * Makes the username available to the view.
     *
     * @param session the username of the person adding the game
     * @param model the model used to supply data to the view
     * @return the name of the Thymeleaf view for adding a game
     */
    @GetMapping("/addGamePage")
    public String addGame(HttpSession session, Model model) {

        User user = (User) session.getAttribute("loggedInUser");

        if (user == null) {
            return "redirect:/login";
        }

        // Make the username available to the view for use during submission.
        model.addAttribute("user", user);

        model.addAttribute("createGameForm", new CreateGameForm());
        return "addGame";
    }

    /**
     * Processes a submission to add a new game to the catalog.
     * After delegating the operation to the service, redirects the user
     * to the page for adding a game to their collection.
     *
     * @param session the username of the person adding the game
     * @return a redirect to the game collection page
     */
    @PostMapping("/addGame")
    public String addGame(
            @Valid @ModelAttribute CreateGameForm createGameForm,
            BindingResult result,
            HttpSession session,
            Model model
    ) {

        User user = (User) session.getAttribute("loggedInUser");

        if (user == null) {
            return "redirect:/login";
        }

        if (result.hasErrors()) {
            model.addAttribute("user", user);
            return "addGame";
        }

        boolean added = gamesService.addGame(
                user,
                createGameForm.getGameName(),
                createGameForm.getMinPlayers(),
                createGameForm.getMaxPlayers()
        );

        if (!added) {
            result.addError(new ObjectError(
                    "globalError",
                    "The game could not be added. Check that the game doesn't already exist."
            ));
            model.addAttribute("user", user);
            return "addGame";
        }

        // Redirect so the user can continue to the collection workflow.
        return "redirect:/editCollectionPage";
    }


}
