package edu.carroll.cs341.web.controller;

import edu.carroll.cs341.jpa.model.Game;
import edu.carroll.cs341.jpa.model.GameOwned;
import edu.carroll.cs341.jpa.model.User;
import edu.carroll.cs341.service.GamesOwnedService;
import edu.carroll.cs341.service.GamesService;
import edu.carroll.cs341.web.form.AddGameToCollectionForm;
import jakarta.servlet.http.HttpSession;
import jakarta.validation.Valid;
import org.springframework.stereotype.Controller;
import org.springframework.ui.Model;
import org.springframework.validation.BindingResult;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.ModelAttribute;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestParam;

/**
 * Handles web requests for editing games in a user's collection.
 * This controller displays the information for a game owned by a user
 * and processes changes to the selected game and its production year.
 *
 * <p>
 * The controller delegates game retrieval and collection updates to
 * {@link GamesService} and {@link GamesOwnedService} and supplies the
 * information required by the corresponding Thymeleaf view.
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT assisted with reviewing and updating Javadoc comments for this file
 *   in conjunction with Max Montowski. All comments were reviewed by the author.
 *   No code was generated by ChatGPT.</li>
 * </ul>
 */
@Controller
public class EditGameOwnedController {

    /**
     * Service used to retrieve games available in the catalog.
     */
    private final GamesService gamesService;

    /**
     * Service used to retrieve and manage games in a user's collection.
     */
    private final GamesOwnedService gamesOwnedService;

    /**
     * Constructs the controller with the services required to retrieve
     * available games and manage game ownership records.
     *
     * @param gamesService      service for retrieving available games
     * @param gamesOwnedService service for managing owned games
     */
    public EditGameOwnedController(GamesService gamesService, GamesOwnedService gamesOwnedService) {
        this.gamesService = gamesService;
        this.gamesOwnedService = gamesOwnedService;
    }

    /**
     * Displays the page for editing a game in the logged-in user's collection.
     * Retrieves the ownership record, available games, and current production year
     * and adds them to the model for use by the view.
     *
     * @param session     the HTTP session containing the logged-in user
     * @param gameOwnedID the ID of the game ownership record to edit
     * @param model       the model used to supply data to the view
     * @return the edit game view, a redirect to the collection page if the
     * ownership record cannot be found, or a redirect to the login page
     * if no user is logged in
     */
    @GetMapping("/editGameOwnedPage")
    public String editGameOwnedPage(
            HttpSession session,
            @RequestParam Long gameOwnedID,
            Model model) {
        // Retrieve the logged-in user from the session.
        User user = (User) session.getAttribute("loggedInUser");

        // Ensure the user is logged in, redirect to login page if not.
        if (user == null) {
            return "redirect:/login";
        }

        // Find the ownership record belonging to this user.
        GameOwned gameOwned = gamesOwnedService.getGameOwnedByID(user, gameOwnedID);

        // Return to the collection page if the ownership record cannot be found.
        if (gameOwned == null) {
            return "redirect:/editCollectionPage";
        }

        // Add the user, ownership record, and available games to the model.
        model.addAttribute("user", user);
        model.addAttribute("gameOwned", gameOwned);
        model.addAttribute("games", gamesService.getAvailableGames(user));

        // Set the currently selected game in the form.
        model.addAttribute("selectedGameID", gameOwned.getGame().getGameID());

        // Create the form and populate it with the current production year.
        AddGameToCollectionForm form = new AddGameToCollectionForm();
        form.setYearProduced(gameOwned.getYearProduced());
        model.addAttribute("addGameToCollectionForm", form);
        return "editGameOwned";
    }

    /**
     * Processes changes to a game in the logged-in user's collection.
     * Validates the submitted form, retrieves the selected game, and delegates
     * the collection update to the games owned service.
     *
     * @param session       the HTTP session containing the logged-in user
     * @param gameID        the ID of the game selected from the available games
     * @param form          the form containing the updated production year
     * @param bindingResult the result of validating the submitted form
     * @param model         the model used to supply data to the view if validation fails
     * @param gameOwnedID   the ID of the game ownership record being edited
     * @return a redirect to the collection page after a successful update,
     * the edit game view if validation fails, or a redirect to the login
     * page if no user is logged in
     */
    @PostMapping("/editGameInCollection")
    public String editGameInCollection(HttpSession session, Long gameID,
                                       @Valid @ModelAttribute("addGameToCollectionForm") AddGameToCollectionForm form,
                                       BindingResult bindingResult,
                                       Model model, Long gameOwnedID) {
        // Retrieve the logged-in user from the session.
        User user = (User) session.getAttribute("loggedInUser");

        // Ensure the user is logged in, redirect to login page if not.
        if (user == null) {
            return "redirect:/login";
        }

        // Find the ownership record belonging to this user.
        GameOwned gameOwned = gamesOwnedService.getGameOwnedByID(user, gameOwnedID);

        // Return to the collection page if the ownership record cannot be found.
        if (gameOwned == null) {
            return "redirect:/editCollectionPage";
        }

        // Redisplay the edit page if the submitted form contains validation errors.
        if (bindingResult.hasErrors()) {
            model.addAttribute("user", user);
            model.addAttribute("gameOwned", gameOwned);
            model.addAttribute("games", gamesService.getAvailableGames(user));
            model.addAttribute("selectedGameID", gameID);
            return "editGameOwned";
        }

        // Retrieve the game selected by the user.
        Game game = gamesService.getGameByGameID(gameID);

        // Update the ownership record with the selected game and production year.
        gamesOwnedService.editGameInCollection(user, gameOwnedID, game, form.getYearProduced());

        // Redirect to the collection view after processing the submission.
        return "redirect:/editCollectionPage";
    }
}