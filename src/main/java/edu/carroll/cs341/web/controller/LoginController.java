package edu.carroll.cs341.web.controller;

import edu.carroll.cs341.service.UserService;
import edu.carroll.cs341.web.form.LoginForm;
import jakarta.validation.Valid;
import org.springframework.stereotype.Controller;
import org.springframework.ui.Model;
import org.springframework.validation.BindingResult;
import org.springframework.validation.ObjectError;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.ModelAttribute;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.servlet.mvc.support.RedirectAttributes;

/**
 * Handles web requests related to user login.
 * Displays the login page, validates submitted login information,
 * and redirects users to the home page when their credentials are valid.
 *
 * The controller delegates user validation to {@link UserService} and uses
 * Spring validation to handle errors in submitted login forms.
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author. No code was generated by ChatGPT.</li>
 * </ul>
 */
@Controller
public class LoginController {

    /** Service used to validate user credentials. */
    private final UserService userService;

    /**
     * Constructs the login controller with the service required to validate
     * user credentials.
     *
     * @param userService service used for user-related operations
     */
    public LoginController(UserService userService) {
        this.userService = userService;
    }

    /**
     * Displays the login page and adds an empty login form to the model.
     *
     * @param model the model used to provide attributes to the view
     * @return the name of the login view
     */
    @GetMapping("/login")
    public String loginGet(Model model) {
        // Provide a new form object for the user to fill out.
        model.addAttribute("loginForm", new LoginForm());

        return "login";
    }

    /**
     * Processes a submitted login form.
     * Returns the login page if form validation fails or if the credentials
     * do not match a known user. Otherwise, redirects to the home page.
     *
     * @param loginForm the submitted login form containing the username
     *                  and password
     * @param result the result of validating the submitted form
     * @param attrs attributes to include in the redirect URL
     * @return the login view when validation fails, or a redirect to the home page
     */
    @PostMapping("/login")
    public String loginPost(@Valid @ModelAttribute LoginForm loginForm, BindingResult result, RedirectAttributes attrs) {
        // Return to the form if any field-level validation rules fail.
        if (result.hasErrors()) {
            return "login";
        }

        // Check the submitted credentials against the user service.
        if (!userService.validateUser(loginForm.getUsername(), loginForm.getPassword())) {
            // Add a form-level error when the credentials are not recognized.
            result.addError(new ObjectError("globalError", "Username and password do not match known users"));
            return "login";
        }

        // Preserve the username as a redirect attribute for the home page.
        attrs.addAttribute("username", loginForm.getUsername());
        
        return "redirect:/homePage";
    }
}