package edu.carroll.cs341.web.controller;

import edu.carroll.cs341.jpa.model.User;
import edu.carroll.cs341.service.UserService;
import edu.carroll.cs341.web.form.LoginForm;
import jakarta.servlet.http.HttpSession;
import jakarta.validation.Valid;
import org.springframework.stereotype.Controller;
import org.springframework.ui.Model;
import org.springframework.validation.BindingResult;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.ModelAttribute;
import org.springframework.web.bind.annotation.PostMapping;

/**
 * Controller responsible for displaying the password entry page and
 * processing password confirmation requests.
 * <p>
 * Allows logged-in users to access a page where they can enter their
 * password before proceeding to the password change page. Stores the
 * logged-in user in the password session and sets a five-minute session
 * inactivity limit for the password change process.
 * <p>
 * <b>Sources Used:</b>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author. No code was generated by ChatGPT.</li>
 * </ul>
 */
@Controller
public class EnterPasswordPageController {

    /**
     * Service used to perform user account operations.
     */
    private final UserService userService;

    /**
     * Constructs the password entry page controller.
     *
     * @param userService the service used to perform user account operations
     */
    public EnterPasswordPageController(UserService userService) {
        this.userService = userService;
    }

    /**
     * Displays the password entry page for the currently logged-in user.
     * <p>
     * Retrieves the logged-in user from the HTTP session. If no user is
     * logged in, redirects to the login page. Otherwise, adds the user
     * and a new login form to the model.
     *
     * @param session the HTTP session containing the logged-in user
     * @param model the model used to provide attributes to the view
     * @return the password entry page, or a redirect to the login page
     */
    @GetMapping("/enterPasswordPage")
    public String enterPasswordPageGet(HttpSession session, Model model) {
        User user = (User) session.getAttribute("loggedInUser");

        if (user == null) {
            return "redirect:/login";
        }

        // Make the username available to the view for subsequent form submissions.
        model.addAttribute("user", user);
        model.addAttribute("loginForm", new LoginForm());

        return "enterPasswordPage";
    }

    /**
     * Processes the submitted password entry form.
     * <p>
     * Retrieves the logged-in user from the HTTP session. If no user is
     * logged in, redirects to the login page. If the submitted form contains
     * validation errors, returns to the password entry page. Otherwise,
     * stores the user in the password session, sets the session inactivity
     * limit to five minutes, and redirects to the password change page.
     *
     * @param loginForm the form containing the submitted password information
     * @param result the result of validating the submitted form
     * @param session the HTTP session containing the logged-in user
     * @param passwordSession the HTTP session used for the password change process
     * @param model the model used to provide attributes to the view
     * @return the password entry page, a redirect to the login page, or a
     * redirect to the password change page
     */
    @PostMapping("/enterPasswordPage")
    public String enterPasswordPagePost(@Valid @ModelAttribute LoginForm loginForm, BindingResult result, HttpSession session, HttpSession passwordSession, Model model) {
        User user = (User) session.getAttribute("loggedInUser");

        if (user == null) {
            return "redirect:/login";
        }

        if (result.hasErrors()) {
            model.addAttribute("user", user);
            return "enterPasswordPage";
        }

        passwordSession.setMaxInactiveInterval(5*60);
        passwordSession.setAttribute("loggedInUser", user);

        return "redirect:/changePasswordPage";

    }
}
