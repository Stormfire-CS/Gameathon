package edu.carroll.cs341.web.controller;

import edu.carroll.cs341.jpa.model.User;
import jakarta.servlet.http.HttpSession;
import org.springframework.stereotype.Controller;
import org.springframework.ui.Model;
import org.springframework.web.bind.annotation.GetMapping;

/**
 * Handles web requests for the owner page.
 * Retrieves the username from the request and makes it available
 * to the owner page view.
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author. No code was generated by ChatGPT.</li>
 * </ul>
 */
@Controller
public class OwnerPageController {

    /**
     * Displays the owner page and adds the username to the model
     * so that it can be accessed by the view.
     *
     * @param session the username of the user accessing the owner page
     * @param model the model used to provide attributes to the view
     * @return the name of the owner page view
     */
    @GetMapping("/ownerPage")
    public String ownerPage(HttpSession session, Model model) {

        User user = (User) session.getAttribute("loggedInUser");

        if (user == null) {
            return "redirect:/login";
        }

        // Make the username available to the owner page template.
        model.addAttribute("user", user);
        
        return "ownerPage";
    }
}
