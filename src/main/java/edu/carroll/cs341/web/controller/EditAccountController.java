package edu.carroll.cs341.web.controller;

import edu.carroll.cs341.jpa.model.User;
import edu.carroll.cs341.service.UserService;
import edu.carroll.cs341.web.form.EditNameForm;
import jakarta.persistence.ManyToOne;
import jakarta.servlet.http.HttpSession;
import jakarta.validation.Valid;
import org.springframework.stereotype.Controller;
import org.springframework.ui.Model;
import org.springframework.validation.BindingResult;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.ModelAttribute;
import org.springframework.web.bind.annotation.PostMapping;

/**
 * Controller responsible for displaying and processing account editing requests.
 * <p>
 * Allows logged-in users to access the account editing page and submit a
 * request to change the name associated with their account. Users who are
 * not logged in are redirected to the login page.
 * <p>
 * <b>Sources Used:</b>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author. No code was generated by ChatGPT.</li>
 * </ul>
 */
@Controller
public class EditAccountController {

    /**
     * Service used to perform user account operations.
     */
    UserService userService;

    /**
     * Constructs the account editing controller.
     *
     * @param userService the service used to perform user account operations
     */
    public EditAccountController(UserService userService) {
        this.userService = userService;
    }

    /**
     * Displays the account editing page for the currently logged-in user.
     * <p>
     * Retrieves the logged-in user from the HTTP session. If no user is
     * logged in, redirects the request to the login page. Otherwise, adds
     * the user and a new name editing form to the model.
     *
     * @param session the HTTP session containing the logged-in user
     * @param model the model used to provide attributes to the view
     * @return the account editing page, or a redirect to the login page
     */
    @GetMapping("/editAccount")
    public String editAccountGet(HttpSession session, Model model) {
        User user = (User) session.getAttribute("loggedInUser");

        if (user == null) {
            return "redirect:/login";
        }

        // Make the username available to the view for subsequent form submissions.
        model.addAttribute("user", user);
        model.addAttribute("editNameForm", new EditNameForm());

        return "editAccount";
    }

    /**
     * Processes a submitted request to change the logged-in user's name.
     * <p>
     * Retrieves the logged-in user from the HTTP session and validates the
     * submitted name editing form. If the user is not logged in, redirects
     * to the login page. If the form contains validation errors, returns
     * to the account editing page with the user added back to the model.
     * Otherwise, passes the user and submitted name to the user service.
     *
     * @param session the HTTP session containing the logged-in user
     * @param model the model used to provide attributes to the view
     * @param editNameForm the form containing the submitted new name
     * @param bindingResult the result of validating the submitted form
     * @return the account editing page, or a redirect to the login page
     */
    @PostMapping("/editAccount")
    public String editAccountPost(HttpSession session, Model model, @Valid @ModelAttribute EditNameForm editNameForm, BindingResult bindingResult) {
        User user = (User) session.getAttribute("loggedInUser");

        if (user == null) {
            return "redirect:/login";
        }

        if(bindingResult.hasErrors()) {
            model.addAttribute("user", user);
            return "editAccount";
        }

        userService.renameUser(user, editNameForm.getName());

        return "/editAccount";
    }
}
