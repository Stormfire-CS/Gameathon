package edu.carroll.cs341.web.controller;

import edu.carroll.cs341.jpa.model.User;
import edu.carroll.cs341.service.UserService;
import edu.carroll.cs341.web.form.EditPasswordForm;
import jakarta.servlet.http.HttpSession;
import jakarta.validation.Valid;
import org.springframework.stereotype.Controller;
import org.springframework.ui.Model;
import org.springframework.validation.BindingResult;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.ModelAttribute;
import org.springframework.web.bind.annotation.PostMapping;

/**
 * Controller responsible for displaying and processing password change requests.
 * <p>
 * Allows logged-in users to access the password change page and submit a new
 * password for their account. Verifies that the user is present in the HTTP
 * session before allowing access to the password change functionality.
 * <p>
 * <b>Sources Used:</b>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author. No code was generated by ChatGPT.</li>
 * </ul>
 */
@Controller
public class ChangePasswordPageController {

    /**
     * Service used to perform user account operations.
     */
    private final UserService userService;

    /**
     * Constructs the password change page controller.
     *
     * @param userService the service used to perform user account operations
     */
    public ChangePasswordPageController(UserService userService) {
        this.userService = userService;
    }

    /**
     * Displays the password change page for the currently logged-in user.
     * <p>
     * Retrieves the logged-in user from the HTTP session. If no user is
     * logged in, redirects to the login page. Also checks for a user in the
     * password session before displaying the page. If that user is not
     * present, redirects to the account editing page.
     *
     * @param session the HTTP session containing the logged-in user
     * @param passwordSession the HTTP session checked for password change access
     * @param model the model used to provide attributes to the view
     * @return the password change page, or a redirect to another page
     */
    @GetMapping("/changePasswordPage")
    public String changePassword (HttpSession session, HttpSession passwordSession, Model model) {

        User user = (User) session.getAttribute("loggedInUser");

        if (user == null) {
            return "redirect:/login";
        }

        User passUser = (User) passwordSession.getAttribute("loggedInUser");

        if (passUser == null) {
            return "redirect:/editAccount";
        }

        model.addAttribute("user", user);
        model.addAttribute("editPasswordForm", new EditPasswordForm());

        return "changePasswordPage";
    }

    /**
     * Processes a submitted request to change the logged-in user's password.
     * <p>
     * Retrieves the logged-in user from the HTTP session and checks for a
     * user in the password session. If either check fails, redirects to the
     * appropriate page. If the submitted form contains validation errors,
     * returns to the password change page. Otherwise, passes the user and
     * submitted password to the user service and redirects to the home page.
     *
     * @param session the HTTP session containing the logged-in user
     * @param passwordSession the HTTP session checked for password change access
     * @param editPasswordForm the form containing the submitted password values
     * @param bindingResult the result of validating the submitted form
     * @param model the model used to provide attributes to the view
     * @return a redirect to the login page, account editing page, password
     * change page, or home page
     */
    @PostMapping("/changePassword")
    public String changePassword(HttpSession session, HttpSession passwordSession, @Valid @ModelAttribute("editPasswordForm") EditPasswordForm editPasswordForm,
                                 BindingResult bindingResult, Model model)
    {
        User user = (User) session.getAttribute("loggedInUser");

        if (user == null) {
            return "redirect:/login";
        }

        User passUser = (User) passwordSession.getAttribute("loggedInUser");

        if (passUser == null) {
            return "redirect:/editAccount";
        }

        if (bindingResult.hasErrors()) {
            model.addAttribute("user", user);
            return "changePasswordPage";
        }

        userService.changeUsersPassword(user, editPasswordForm.getPassword1());

        return "redirect:/";
    }
}
