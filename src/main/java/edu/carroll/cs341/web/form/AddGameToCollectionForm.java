package edu.carroll.cs341.web.form;

import jakarta.validation.constraints.AssertTrue;
import jakarta.validation.constraints.Min;

import java.time.Year;

/**
 * Represents the form data submitted when a user adds a game to their collection.
 * Stores the year the game was produced and validates that the year falls within
 * the permitted range.
 *
 * <p>The {@link Min} annotation ensures that the year is not earlier than
 * 2000 B.C. The {@link AssertTrue} annotation ensures that the year is not
 * more than two years in the future.</p>
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT – Assisted with writing Javadoc comments for this file
 *   in conjunction with Max Montowski.</li>
 *   <li>All comments were reviewed by the author. No code was generated by ChatGPT.</li>
 * </ul>
 *
 * @author Max Montowski
 */
public class AddGameToCollectionForm {

    /** The year the game was produced, represented as an integer. */
    @Min(value = -2000, message = "Game cannot be older than 2000 B.C.")
    private Integer yearProduced;

    /**
     * Returns the year the game was produced.
     *
     * @return the year the game was produced, or {@code null} if no year was provided
     */
    public Integer getYearProduced() {
        return yearProduced;
    }

    /**
     * Sets the year the game was produced.
     *
     * @param yearProduced the year the game was produced
     */
    public void setYearProduced(Integer yearProduced) {
        this.yearProduced = yearProduced;
    }

    /**
     * Validates that the production year is not more than two years
     * beyond the current year.
     *
     * <p>If no production year was provided, this method returns {@code true},
     * allowing the field to remain optional.</p>
     *
     * @return {@code true} if the year is not more than two years in the future
     *         or no year was provided; {@code false} otherwise
     */
    @AssertTrue(message = "Game cannot be produced more than two years in the future")
    public boolean isYearProducedValid() {
        if (yearProduced == null) {
            return true;
        }

        return yearProduced <= Year.now().getValue() + 2;

    }
}
