package edu.carroll.cs341.web.form;

import jakarta.validation.constraints.Size;

/**
 * Represents the form data submitted when a user creates a new account.
 * Stores the username and two password entries so that the submitted
 * information can be validated before the account creation process continues.
 *
 * The {@link Size} annotations define minimum length requirements for
 * the username and both password fields.
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author. No code was generated by ChatGPT.</li>
 * </ul>
 */
public class CreateUserForm {

    /** Username entered by the user; must contain at least two characters. */
    @Size(min = 2, message = "Username must be at least 2 characters long")
    private String username;

    /** First password entry; must contain at least eight characters. */
    @Size(min = 8, message = "Password must be at least 8 characters long")
    private String password1;

    /** Confirmation password entry; must contain at least eight characters. */
    @Size(min = 8, message = "Password must be at least 8 characters long")
    private String password2;

    /**
     * Retrieves the username entered in the form.
     *
     * @return the submitted username
     */
    public String getUsername() {
        return username;
    }

    /**
     * Sets the username entered in the form.
     *
     * @param username the username to store
     */
    public void setUsername(String username) {
        this.username = username;
    }

    /**
     * Retrieves the first password entry.
     *
     * @return the first submitted password
     */
    public String getPassword1() {
        return password1;
    }

    /**
     * Sets the first password entry.
     *
     * @param password1 the password to store
     */
    public void setPassword1(String password1) {
        this.password1 = password1;
    }

    /**
     * Retrieves the password confirmation entry.
     *
     * @return the second submitted password
     */
    public String getPassword2() {
        return password2;
    }

    /**
     * Sets the password confirmation entry.
     *
     * @param password2 the confirmation password to store
     */
    public void setPassword2(String password2) {
        this.password2 = password2;
    }


}
