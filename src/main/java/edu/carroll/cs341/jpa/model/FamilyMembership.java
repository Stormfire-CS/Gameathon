package edu.carroll.cs341.jpa.model;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.util.Objects;

import static org.aspectj.util.LangUtil.EOL;

/**
 * Represents a user's membership or join request for a family.
 *
 * <p>This entity maps to the FamilyMembership table and stores the membership
 * identifier, the family it is associated with, the user it is associated with, and the
 * current membership status.</p>
 *
 * <p>The status field can be used to track whether a user's request to join
 * a family is pending, accepted, or rejected.</p>
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author. No code was generated by ChatGPT.</li>
 * </ul>
 */
@Entity
@Table(name = "FamilyMembership")
public class FamilyMembership {

    /**
     * The unique identifier assigned to this membership record.
     */
    @Id
    @GeneratedValue
    private Long membershipID;

    /**
     * The family associated with this membership.
     */
    @ManyToOne
    @JoinColumn(name = "family", nullable = false)
    private Family family;

    /**
     * The user associated with this membership.
     */
    @ManyToOne
    @JoinColumn(name = "user", nullable = false)
    private User user;

    /**
     * The current status of the user's membership or join request.
     */
    @Column(name = "status", nullable = false)
    private String status;

    /**
     * Creates an empty FamilyMembership object.
     *
     * <p>This constructor is required by JPA when retrieving membership
     * records from the database.</p>
     */
    public FamilyMembership() {
    }

    /**
     * Creates a membership record for a specific family and user.
     *
     * @param family the family associated with the membership
     * @param user   the user associated with the membership
     * @param status the initial status of the membership
     */
    public FamilyMembership(Family family, User user, String status) {
        this.family = family;
        this.user = user;
        this.status = status;
    }

    /**
     * Retrieves the membership record's database identifier.
     *
     * @return the unique membership ID
     */
    public Long getMembershipID() {
        return membershipID;
    }

    /**
     * Sets the membership record's database identifier.
     *
     * @param membershipID the ID to assign to the membership record
     */
    public void setMembershipID(Long membershipID) {
        this.membershipID = membershipID;
    }

    /**
     * Retrieves the associated family.
     *
     * @return the family
     */
    public Family getFamily() {
        return family;
    }

    /**
     * Sets the associated family.
     *
     * @param family the family to assign to the membership
     */
    public void setFamily(Family family) {
        this.family = family;
    }

    /**
     * Retrieves the associated user.
     *
     * @return the user
     */
    public User getUser() {
        return user;
    }

    /**
     * Sets the associated user.
     *
     * @param user the user to assign to the membership
     */
    public void setUser(User user) {
        this.user = user;
    }

    /**
     * Retrieves the current membership status.
     *
     * @return the membership status
     */
    public String getStatus() {
        return status;
    }

    /**
     * Sets the current membership status.
     *
     * @param status the status to assign to the membership
     */
    public void setStatus(String status) {
        this.status = status;
    }

    /**
     * Returns a readable representation of the family membership.
     *
     * <p>The representation includes the membership ID, the family and user associated with it,
     * and the status of the membership.</p>
     *
     * @return a string containing the family memberships identifying information
     */
    @Override
    public String toString() {
        StringBuilder builder = new StringBuilder();
        builder.append("Family membership: membership ID = ").append(membershipID).append(EOL);
        builder.append("family = ").append(family);
        builder.append("user = ").append(user);
        builder.append("status = ").append(status);
        return builder.toString();
    }

    /**
     * Compares this family membership with another object for equality.
     *
     * <p>Two family memberships are considered equal when their family, user and status
     * match.</p>
     *
     * @param o the object to compare with this family membership
     * @return true if the objects represent equal family memberships; false otherwise
     */
    @Override
    public boolean equals(Object o) {
        if (this == o)
            return true;
        if (o == null || getClass() != o.getClass())
            return false;

        FamilyMembership familyMembership = (FamilyMembership) o;
        return (family.equals(familyMembership.family) && user.equals(familyMembership.user) && status.equals(familyMembership.status));
    }

    /**
     * Calculates a hash code using the family user and status.
     *
     * @return the hash code for this family membership
     */
    @Override
    public int hashCode() {
        return Objects.hash(family, user, status);
    }
}
