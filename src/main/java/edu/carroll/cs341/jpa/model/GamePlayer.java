package edu.carroll.cs341.jpa.model;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

import static org.aspectj.util.LangUtil.EOL;

/**
 * Represents a player who can participate in games.
 *
 * <p>This entity maps to the GamePlayers table and stores the player's unique
 * identifier, name, and optional association with an owner account.</p>
 *
 * <p>A game player may be associated with an owner through the ownerID field.
 * If no owner is associated with the player, the ownerID is {@code null}.</p>
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author. No code was generated by ChatGPT.</li>
 * </ul>
 */
@Entity
@Table(name = "GamePlayers")
public class GamePlayer {

    /**
     * The unique identifier assigned to this game player.
     */
    @Id
    @GeneratedValue
    private Long gamePlayerID;

    /**
     * The name of the game player.
     */
    @Column(name = "name", nullable = false)
    private String name;

    /**
     * The ID of the owner associated with this game player, if any.
     */
    @Column(name = "ownerID", unique = true)
    private Long ownerID;

    /**
     * Creates an empty GamePlayer object.
     *
     * <p>This constructor is required by JPA when retrieving player records
     * from the database.</p>
     */
    public GamePlayer() {
    }

    /**
     * Creates a game player with the specified name.
     *
     * @param name the name assigned to the game player
     */
    public GamePlayer(String name) {
        this.name = name;
    }

    /**
     * Retrieves the game player's database identifier.
     *
     * @return the unique game player ID
     */
    public Long getGamePlayerID() {
        return gamePlayerID;
    }

    /**
     * Sets the game player's database identifier.
     *
     * @param gamePlayerID the ID to assign to the game player
     */
    public void setGamePlayerID(Long gamePlayerID) {
        this.gamePlayerID = gamePlayerID;
    }

    /**
     * Retrieves the game player's name.
     *
     * @return the player's name
     */
    public String getName() {
        return name;
    }

    /**
     * Sets the game player's name.
     *
     * @param name the name to assign to the game player
     */
    public void setName(String name) {
        this.name = name;
    }

    /**
     * Retrieves the ID of the owner associated with this game player.
     *
     * @return the owner ID, or {@code null} if no owner is associated
     */
    public Long getOwnerID() {
        return ownerID;
    }

    /**
     * Sets the ID of the owner associated with this game player.
     *
     * @param ownerID the owner ID to associate with the game player
     */
    public void setOwnerID(Long ownerID) {
        this.ownerID = ownerID;
    }

    /**
     * Returns a readable representation of the game player.
     *
     * <p>The representation includes the player's ID and name. It also
     * includes the owner ID if one exists, or a message indicating that
     * no owner is associated with the player.</p>
     *
     * @return a string containing the game player's information
     */
    @Override
    public String toString() {
        StringBuilder builder = new StringBuilder();
        builder.append("Game Player: game player ID").append(gamePlayerID).append(EOL);
        builder.append("name = ").append(name).append(EOL);
        if (ownerID != null) {
            builder.append("owner ID").append(ownerID).append(EOL);
        } else {
            builder.append("No Owner Assocaited With game player.");
        }
        return builder.toString();
    }
}
