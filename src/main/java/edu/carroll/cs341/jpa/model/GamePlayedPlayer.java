package edu.carroll.cs341.jpa.model;

import jakarta.persistence.*;

import static org.aspectj.util.LangUtil.EOL;

/**
 * Represents a player's participation in a game-play session.
 *
 * <p>This entity maps to the GamePlayedPlayers table and stores the unique
 * identifier for the participation record, the player's ID, their score,
 * and whether they won the game.</p>
 *
 * <p>The score and win status are optional, allowing a record to exist before
 * the player's results have been recorded.</p>
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author. No code was generated by ChatGPT.</li>
 * </ul>
 */
@Entity
@Table(name = "GamePlayedPlayers")
public class GamePlayedPlayer {

    /** The unique identifier assigned to this player participation record. */
    @Id
    @GeneratedValue
    private Long gamePlayedPlayerID;

    /** The ID of the player associated with this game-play record. */
    @Column(name = "playerID", nullable = false, unique = true)
    private Long playerID;

    /** The player's score for the game, if it has been recorded. */
    @Column(name = "score")
    private Integer score;

    /** Whether the player won the game, if the result has been recorded. */
    @Column(name = "didWin")
    private Boolean didWin;

    /**
     * Creates an empty GamePlayedPlayer object.
     *
     * <p>This constructor is required by JPA when retrieving records
     * from the database.</p>
     */
    public GamePlayedPlayer() {
    }

    /**
     * Creates a player participation record for a specified player.
     *
     * @param playerID the ID of the player associated with the record
     */
    public GamePlayedPlayer(Long playerID) {
        this.playerID = playerID;
    }

    /**
     * Retrieves the participation record's database identifier.
     *
     * @return the unique game-play player ID
     */
    public Long getGamePlayedPlayerID() {
        return gamePlayedPlayerID;
    }

    /**
     * Sets the participation record's database identifier.
     *
     * @param gamePlayedPlayerID the ID to assign to the record
     */
    public void setGamePlayedPlayerID(Long gamePlayedPlayerID) {
        this.gamePlayedPlayerID = gamePlayedPlayerID;
    }

    /**
     * Retrieves the ID of the player associated with this record.
     *
     * @return the player's ID
     */
    public Long getPlayerID() {
        return playerID;
    }

    /**
     * Sets the ID of the player associated with this record.
     *
     * @param playerID the player's ID to assign to the record
     */
    public void setPlayerID(Long playerID) {
        this.playerID = playerID;
    }

    /**
     * Retrieves the player's score for the game.
     *
     * @return the player's score, or {@code null} if it has not been recorded
     */
    public Integer getScore() {
        return score;
    }

    /**
     * Sets the player's score for the game.
     *
     * @param score the score to assign to the player
     */
    public void setScore(Integer score) {
        this.score = score;
    }

    /**
     * Retrieves whether the player won the game.
     *
     * @return {@code true} if the player won, {@code false} if they did not,
     *         or {@code null} if the result has not been recorded
     */
    public Boolean getDidWin() {
        return didWin;
    }

    /**
     * Sets whether the player won the game.
     *
     * @param didWin the player's win status
     */
    public void setDidWin(Boolean didWin) {
        this.didWin = didWin;
    }

    /**
     * Returns a readable representation of the player participation record.
     *
     * <p>The representation includes the record ID and player ID. The score
     * and win status are included only when they are not {@code null}.</p>
     *
     * @return a string containing the participation record's information
     */
    @Override
    public String toString() {
        StringBuilder builder = new StringBuilder();
        builder.append("Game played player: game played player ID = ").append(gamePlayedPlayerID).append(EOL);
        builder.append("player ID = ").append(playerID).append(EOL);
        if (score != null) {
            builder.append("score = ").append(score).append(EOL);
        }
        if (didWin != null) {
            builder.append("Did player win boolean = ").append(didWin);
        }
        return builder.toString();
    }

}
