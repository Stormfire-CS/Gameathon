package edu.carroll.cs341.jpa.model;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import java.util.Objects;

import static org.aspectj.util.LangUtil.EOL;

/**
 * Represents a game stored in the database.
 *
 * <p>This entity maps to the Games table and stores a game's unique identifier,
 * name, minimum and maximum player counts, and the user who added it.</p>
 *
 * <p>The user_who_added allows the application to distinguish games added by users
 * from games that are available to everyone.</p>
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author. No code was generated by ChatGPT.</li>
 * </ul>
 */
@Entity
@Table(name = "Game")
public class Game {

    /**
     * The unique identifier assigned to the game by the database.
     */
    @Id
    @GeneratedValue
    private Long gameID;

    /**
     * The name of the game.
     */
    @Column(name = "game_name", nullable = false)
    private String gameName;

    /**
     * The minimum number of players required to play the game.
     */
    @Column(name = "min_players")
    private Integer minPlayers;

    /**
     * The maximum number of players allowed to play the game.
     */
    @Column(name = "max_players")
    private Integer maxPlayers;

    /**
     * The user who added the game, if it was added by a user.
     */
    @ManyToOne
    @JoinColumn(name = "user_who_added")
    private User userWhoAdded;

    /**
     * Creates an empty Game object.
     *
     * <p>This constructor is required by JPA when retrieving game records
     * from the database.</p>
     */
    public Game() {
    }

    /**
     * Creates a game with the specified name.
     *
     * @param gameName the name of the game
     */
    public Game(String gameName) {
        this.gameName = gameName;
    }

    /**
     * Retrieves the game's name.
     *
     * @return the name of the game
     */
    public String getGameName() {
        return gameName;
    }

    /**
     * Sets the game's name.
     *
     * @param gameName the name to assign to the game
     */
    public void setGameName(String gameName) {
        this.gameName = gameName;
    }

    /**
     * Retrieves the game's database identifier.
     *
     * @return the unique game ID
     */
    public Long getGameID() {
        return gameID;
    }

    /**
     * Sets the game's database identifier.
     *
     * @param gameID the ID to assign to the game
     */
    public void setGameID(Long gameID) {
        this.gameID = gameID;
    }

    /**
     * Retrieves the minimum number of players required to play the game.
     *
     * @return the minimum player count, or {@code null} if it is not set
     */
    public Integer getMinPlayers() {
        return minPlayers;
    }

    /**
     * Sets the minimum number of players required to play the game.
     *
     * @param minPlayers the minimum player count
     */
    public void setMinPlayers(Integer minPlayers) {
        this.minPlayers = minPlayers;
    }

    /**
     * Retrieves the maximum number of players allowed to play the game.
     *
     * @return the maximum player count, or {@code null} if it is not set
     */
    public Integer getMaxPlayers() {
        return maxPlayers;
    }

    /**
     * Sets the maximum number of players allowed to play the game.
     *
     * @param maxPlayers the maximum player count
     */
    public void setMaxPlayers(Integer maxPlayers) {
        this.maxPlayers = maxPlayers;
    }

    /**
     * Retrieves the user who added the game.
     *
     * @return the user, or {@code null} if no user is assigned
     */
    public User getUserWhoAdded() {
        return userWhoAdded;
    }

    /**
     * Sets the user who added the game.
     *
     * @param userWhoAdded the user to associate with the game
     */
    public void setUserWhoAdded(User userWhoAdded) {
        this.userWhoAdded = userWhoAdded;
    }

    /**
     * Returns a readable representation of the game.
     *
     * <p>The representation includes the game's ID and any player limits
     * that have been set.</p>
     *
     * @return a string containing the game's identifying information
     */
    @Override
    public String toString() {
        StringBuilder builder = new StringBuilder();
        builder.append("Game: Game_ID = ").append(gameID).append(EOL);
        if (maxPlayers != null) {
            builder.append("Max Number of Players = ").append(maxPlayers).append(EOL);
        }
        if (minPlayers != null) {
            builder.append("Min Number of Players = ").append(minPlayers);
        }
        return builder.toString();
    }

    /**
     * Compares this game with another object for equality.
     *
     * <p>Two games are considered equal when their game name user who added
     * match.</p>
     *
     * @param o the object to compare with this game
     * @return true if the objects represent equal games; false otherwise
     */
    @Override
    public boolean equals(Object o) {
        if (this == o)
            return true;
        if (o == null || getClass() != o.getClass())
            return false;

        Game game = (Game) o;
        return (gameName.equals(game.gameName) && Objects.equals(userWhoAdded, game.userWhoAdded));
    }

    /**
     * Calculates a hash code using the game name and the user who added.
     *
     * @return the hash code for this game
     */
    @Override
    public int hashCode() {
        return Objects.hash(gameName, userWhoAdded);
    }

}
