package edu.carroll.cs341.jpa.model;

import jakarta.persistence.*;

import static org.aspectj.util.LangUtil.EOL;

/**
 * Represents an owner within the application.
 *
 * <p>This entity maps to the Owners table and stores the owner's unique
 * identifier, name, and optional family association.</p>
 *
 * <p>An owner may be associated with a family through the familyID field.
 * The family association is optional.</p>
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author. No code was generated by ChatGPT.</li>
 * </ul>
 */
@Entity
@Table(name = "Owners")
public class Owner {

    /** The unique identifier assigned to this owner. */
    @Id
    @GeneratedValue
    private Long ownerID;

    /** The name of the owner. */
    @Column(name = "name", nullable = false, unique = false)
    private String name;

    /** The ID of the family associated with this owner, if any. */
    @Column(name = "familyID", nullable = true, unique = false)
    private Long familyID;

    /**
     * Creates an empty Owner object.
     *
     * <p>This constructor is required by JPA when retrieving owner records
     * from the database.</p>
     */
    public Owner() {
    }

    /**
     * Creates an owner with the specified name.
     *
     * @param name the name assigned to the owner
     */
    public Owner(String name) {
        this.name = name;
    }

    /**
     * Retrieves the owner's database identifier.
     *
     * @return the unique owner ID
     */
    public Long getOwnerID() {
        return ownerID;
    }

    /**
     * Sets the owner's database identifier.
     *
     * @param ownerID the ID to assign to the owner
     */
    public void setOwnerID(Long ownerID) {
        this.ownerID = ownerID;
    }

    /**
     * Retrieves the owner's name.
     *
     * @return the owner's name
     */
    public String getName() {
        return name;
    }

    /**
     * Sets the owner's name.
     *
     * @param name the name to assign to the owner
     */
    public void setName(String name) {
        this.name = name;
    }

    /**
     * Returns a readable representation of the owner.
     *
     * <p>The representation includes the owner's ID and name.</p>
     *
     * @return a string containing the owner's information
     */
    @Override
    public String toString() {
        StringBuilder builder = new StringBuilder();
        builder.append("Owner: ownerID").append(ownerID).append(EOL);
        builder.append("name = ").append(name);
        return builder.toString();
    }

    @Override
    public boolean equals(Object o) {
        if (this == o)
            return true;
        if (o == null || getClass() != o.getClass())
            return false;

        Owner owner = (Owner) o;
        return (ownerID.equals(owner.ownerID));
    }


}
