package edu.carroll.cs341.jpa.model;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.OneToOne;
import jakarta.persistence.Table;

import java.util.Objects;

import static org.aspectj.util.LangUtil.EOL;

/**
 * Represents a family stored in the database.
 *
 * <p>This entity maps to the Families table and stores the family's unique
 * identifier, name, and the user who administers the family.</p>
 *
 * <p>The family name must be unique and cannot be null. Each family must also
 * have an administrator assigned to it.</p>
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author. No code was generated by ChatGPT.</li>
 * </ul>
 */
@Entity
@Table(name = "Family")
public class Family {

    /**
     * The unique identifier assigned to the family by the database.
     */
    @Id
    @GeneratedValue
    private Long familyID;

    /**
     * The unique name assigned to the family.
     */
    @Column(name = "family_name", nullable = false)
    private String familyName;

    /**
     * The user who administers the family.
     */
    @OneToOne
    @JoinColumn(name = "family_admin", nullable = false, unique = true)
    private User familyAdmin;

    /**
     * Creates an empty Family object.
     *
     * <p>This constructor is required by JPA when retrieving family records
     * from the database.</p>
     */
    public Family() {
    }

    /**
     * Creates a family with a name and an assigned administrator.
     *
     * @param familyName  the name of the family
     * @param familyAdmin the user who administers the family
     */
    public Family(String familyName, User familyAdmin) {
        this.familyName = familyName;
        this.familyAdmin = familyAdmin;
    }

    /**
     * Retrieves the family's database identifier.
     *
     * @return the family's unique ID
     */
    public Long getFamilyID() {
        return familyID;
    }

    /**
     * Sets the family's database identifier.
     *
     * @param familyID the ID to assign to the family
     */
    public void setFamilyID(Long familyID) {
        this.familyID = familyID;
    }

    /**
     * Retrieves the family's name.
     *
     * @return the name of the family
     */
    public String getFamilyName() {
        return familyName;
    }

    /**
     * Sets the family's name.
     *
     * @param familyName the name to assign to the family
     */
    public void setFamilyName(String familyName) {
        this.familyName = familyName;
    }

    /**
     * Retrieves the user who is the family administrator.
     *
     * @return the user who administrates
     */
    public User getFamilyAdmin() {
        return familyAdmin;
    }

    /**
     * Sets the user who is the family administrator.
     *
     * @param familyAdmin the user to assign as the family administrator
     */
    public void setFamilyAdmin(User familyAdmin) {
        this.familyAdmin = familyAdmin;
    }

    /**
     * Returns a readable representation of the family.
     *
     * <p>The representation includes the family's ID and name.</p>
     *
     * @return a string containing the family's identifying information
     */
    @Override
    public String toString() {
        StringBuilder builder = new StringBuilder();
        builder.append("Family: family ID = ").append(familyID).append(EOL);
        builder.append("familyName = ").append(familyName);
        return builder.toString();
    }

    /**
     * Compares this family with another object for equality.
     *
     * <p>Two families are considered equal when their family name and family admin
     * match.</p>
     *
     * @param o the object to compare with this family
     * @return true if the objects represent equal families; false otherwise
     */
    @Override
    public boolean equals(Object o) {
        if (this == o)
            return true;
        if (o == null || getClass() != o.getClass())
            return false;

        Family family = (Family) o;
        return (familyName.equals(family.familyName) && familyAdmin.equals(family.familyAdmin));
    }

    /**
     * Calculates a hash code using the family name and the family admin.
     *
     * @return the hash code for this family
     */
    @Override
    public int hashCode() {
        return Objects.hash(familyName, familyAdmin);
    }
}
