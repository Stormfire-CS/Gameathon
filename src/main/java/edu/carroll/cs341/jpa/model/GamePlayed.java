package edu.carroll.cs341.jpa.model;

import jakarta.persistence.*;

import java.util.Date;

import static org.aspectj.util.LangUtil.EOL;

/**
 * Represents a record of a game being played.
 *
 * <p>This entity maps to the GamesPlayed table and stores the unique identifier
 * of the play record, the ID of the owned game that was played, and the date
 * on which the game was played.</p>
 *
 * <p>Each record represents an individual play session associated with a game
 * owned by a user.</p>
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author. No code was generated by ChatGPT.</li>
 * </ul>
 */
@Entity
@Table(name = "GamesPlayed")
public class GamePlayed {

    /** The unique identifier assigned to this game-play record. */
    @Id
    @GeneratedValue
    private Long gamePlayedID;

    /** The ID of the owned game associated with this play session. */
    @Column(name = "ownedGameID", nullable = false)
    private Long ownedGameID;

    /** The date on which the game was played. */
    @Column(name = "datePlayed", nullable = false)
    private Date datePlayed;

    /**
     * Creates an empty GamePlayed object.
     *
     * <p>This constructor is required by JPA when retrieving game-play
     * records from the database.</p>
     */
    public GamePlayed() {
    }

    /**
     * Creates a game-play record for an owned game on a specified date.
     *
     * @param ownedGameID the ID of the owned game that was played
     * @param datePlayed the date on which the game was played
     */
    public GamePlayed(Long ownedGameID, Date datePlayed) {
        this.ownedGameID = ownedGameID;
        this.datePlayed = datePlayed;
    }

    /**
     * Retrieves the game-play record's database identifier.
     *
     * @return the unique game-play ID
     */
    public Long getGamePlayedID() {
        return gamePlayedID;
    }

    /**
     * Sets the game-play record's database identifier.
     *
     * @param gamesPlayedID the ID to assign to the game-play record
     */
    public void setGamePlayedID(Long gamesPlayedID) {
        this.gamePlayedID = gamesPlayedID;
    }

    /**
     * Retrieves the ID of the owned game associated with this play session.
     *
     * @return the owned game ID
     */
    public Long getOwnedGameID() {
        return ownedGameID;
    }

    /**
     * Sets the ID of the owned game associated with this play session.
     *
     * @param ownedGameID the owned game ID to assign to the record
     */
    public void setOwnedGameID(Long ownedGameID) {
        this.ownedGameID = ownedGameID;
    }

    /**
     * Retrieves the date on which the game was played.
     *
     * @return the date the game was played
     */
    public Date getDatePlayed() {
        return datePlayed;
    }

    /**
     * Sets the date on which the game was played.
     *
     * @param datePlayed the date to assign to the play record
     */
    public void setDatePlayed(Date datePlayed) {
        this.datePlayed = datePlayed;
    }

    /**
     * Returns a readable representation of the game-play record.
     *
     * <p>The representation includes the record's ID, the associated owned
     * game ID, and the date the game was played.</p>
     *
     * @return a string containing the game-play record's information
     */
    @Override
    public String toString() {
        StringBuilder builder = new StringBuilder();
        builder.append("Game Played: game played ID = ").append(gamePlayedID).append(EOL);
        builder.append("owned game ID = ").append(ownedGameID).append(EOL);
        builder.append("date played = ").append(datePlayed).append(EOL);
        return builder.toString();
    }

    @Override
    public boolean equals(Object o) {
        if (this == o)
            return true;
        if (o == null || getClass() != o.getClass())
            return false;

        GamePlayed gamePlayed = (GamePlayed) o;
        return (gamePlayedID.equals(gamePlayed.gamePlayedID));
    }
}
