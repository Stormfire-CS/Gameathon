package edu.carroll.cs341.jpa.model;

import jakarta.persistence.*;

import static org.aspectj.util.LangUtil.EOL;

/**
 * Represents a game owned by a particular user.
 *
 * <p>This entity maps to the GamesOwned table and associates a user with a
 * game through a reference to the Game entity. It also stores the year the
 * game was produced, when that information is available.</p>
 *
 * <p>Each record has its own unique identifier and references the user who
 * owns the game and the game itself.</p>
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author. No code was generated by ChatGPT.</li>
 * </ul>
 */
@Entity
@Table(name = "GamesOwned")
public class GameOwned {

    /** The unique identifier assigned to this game ownership record. */
    @GeneratedValue
    @Id
    private Long gameOwnedID;

    /** The game associated with this ownership record. */
    @ManyToOne
    @JoinColumn(name = "gameID", nullable = false)
    private Game game;

    /** The ID of the user who owns the game. */
    @Column(name = "ownerID", nullable = false)
    private Long ownerID;

    /** The year the game was produced, if known. */
    @Column(name = "yearProduced")
    private Integer yearProduced;

    /**
     * Creates an empty GameOwned object.
     *
     * <p>This constructor is required by JPA when retrieving ownership
     * records from the database.</p>
     */
    public GameOwned() {
    }

    /**
     * Creates an ownership record for a specific game and user.
     *
     * @param game the game being owned
     * @param ownerID the ID of the user who owns the game
     */
    public GameOwned(Game game, Long ownerID) {
        this.game = game;
        this.ownerID = ownerID;
    }

    /**
     * Retrieves the ownership record's database identifier.
     *
     * @return the unique game ownership ID
     */
    public Long getGameOwnedID() {
        return gameOwnedID;
    }

    /**
     * Sets the ownership record's database identifier.
     *
     * @param gameOwnedID the ID to assign to the ownership record
     */
    public void setGameOwnedID(Long gameOwnedID) {
        this.gameOwnedID = gameOwnedID;
    }

    /**
     * Retrieves the game associated with this ownership record.
     *
     * @return the associated Game object
     */
    public Game getGame() {
        return game;
    }

    /**
     * Sets the game associated with this ownership record.
     *
     * @param game the Game object to associate with this record
     */
    public void setGame(Game game) {
        this.game = game;
    }

    /**
     * Retrieves the ID of the user who owns the game.
     *
     * @return the owner's user ID
     */
    public Long getOwnerID() {
        return ownerID;
    }

    /**
     * Sets the ID of the user who owns the game.
     *
     * @param ownerID the user ID to associate with this record
     */
    public void setOwnerID(Long ownerID) {
        this.ownerID = ownerID;
    }

    /**
     * Retrieves the year the game was produced.
     *
     * @return the production year, or {@code null} if it is not set
     */
    public Integer getYearProduced() {
        return yearProduced;
    }

    /**
     * Sets the year the game was produced.
     *
     * @param yearProduced the production year to assign to the game
     */
    public void setYearProduced(Integer yearProduced) {
        this.yearProduced = yearProduced;
    }

    /**
     * Returns a readable representation of the game ownership record.
     *
     * <p>The representation includes the ownership ID, game ID, game name,
     * owner ID, and production year when available.</p>
     *
     * @return a string containing the ownership record's information
     */
    @Override
    public String toString() {
        StringBuilder builder = new StringBuilder();
        builder.append("Game Owned ID = ").append(gameOwnedID).append(EOL);
        builder.append("Game ID = ").append(game.getGameID()).append(EOL);
        builder.append("Game Name = ").append(game.getGameName()).append(EOL);
        builder.append("Owner ID = ").append(ownerID);
        if (yearProduced != null) {
            builder.append("Publish Year = ").append(yearProduced).append(EOL);
        }
        return builder.toString();
    }

    @Override
    public boolean equals(Object o) {
        if (this == o)
            return true;
        if (o == null || getClass() != o.getClass())
            return false;

        final GameOwned gameOwned = (GameOwned) o;
        return gameOwnedID.equals(gameOwned.gameOwnedID);
    }
}
