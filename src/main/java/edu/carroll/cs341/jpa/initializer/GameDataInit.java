package edu.carroll.cs341.jpa.initializer;

import edu.carroll.cs341.jpa.model.Game;
import edu.carroll.cs341.jpa.repo.GamesRepository;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.CommandLineRunner;
import org.springframework.stereotype.Component;

import java.io.File;
import java.io.FileNotFoundException;
import java.util.Scanner;

/**
 * Initializes the database with game information stored in a text file.
 *
 * <p>This class implements {@link CommandLineRunner}, allowing the game data
 * to be loaded when the Spring Boot application starts.</p>
 *
 * <p>Each line in the games.txt file contains a game's name, minimum number
 * of players, and maximum number of players, separated by pipe characters.
 * Games that already exist in the database are skipped to prevent duplicates.</p>
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author. No code was generated by ChatGPT.</li>
 * </ul>
 */

@Component
public class GameDataInit implements CommandLineRunner {

    /** Logger used to record database initialization progress and errors. */
    private static final Logger log = LoggerFactory.getLogger(GameDataInit.class);

    /** Repository used to check for existing games and save new game records. */
    private final GamesRepository gamesRepo;

    /**
     * Creates the initializer with access to the games repository.
     *
     * @param gamesRepo the repository used to access game records
     */
    public GameDataInit(GamesRepository gamesRepo) {
        this.gamesRepo = gamesRepo;
    }

    /**
     * Loads game information from games.txt when the application starts.
     *
     * <p>Each line is separated into its individual fields, which are used
     * to create a Game object. If the game is not already in the database,
     * its player limits are set and the game is saved.</p>
     *
     * @param args command-line arguments passed to the application
     */
    @Override
    public void run(String... args) {
        log.info("Starting game data initialization.");

        // Track the number of games added and skipped.
        int gamesAdded = 0;
        int gamesSkipped = 0;
        int gamesFailed = 0;

        try {
            // Open the file containing the initial game information.
            Scanner fileReader = new Scanner(new File("src/main/resources/data/games.txt"));

            // Keeps track of what line number the scanner is on.
            int lineNumber = 0;

            // Process each game entry in the file.
            while (fileReader.hasNextLine()) {
                String line = fileReader.nextLine();
                lineNumber++;

                // Separate the game name and player limits using the pipe delimiter.
                String[] data = line.split("\\|");

                // Check that the line contains all three required fields.
                if (data.length != 3) {
                    log.error("Invalid game entry at line {}: expected 3 fields, found {}.", lineNumber, data.length);
                    gamesFailed++;
                    continue;
                }

                String gameName = data[0].trim();

                // Check that the game name is present.
                if (gameName.isEmpty()) {
                    log.error("Invalid game entry at line {}: game name is empty.", lineNumber);
                    gamesFailed++;
                    continue;
                }

                // Create a game using the name provided in the file.
                Game game = new Game(data[0]);

                // Only add the game if it does not already exist in the database.
                if (!gamesRepo.existsByGameName(data[0])) {

                    int minPlayers;
                    int maxPlayers;

                    try {
                        minPlayers = Integer.parseInt(data[1].trim());
                        maxPlayers = Integer.parseInt(data[2].trim());
                    } catch (NumberFormatException e) {
                        log.error("Invalid player count at line {} for game '{}': '{}'.",
                                lineNumber, gameName, line, e);
                        gamesFailed++;
                        continue;
                    }

                    // Check that the player limits are valid.
                    if (minPlayers < 1 || maxPlayers < minPlayers) {
                        log.error("Invalid player limits at line {} for game '{}': min={}, max={}.", lineNumber, gameName, minPlayers, maxPlayers);
                        gamesFailed++;
                        continue;
                    }

                    // Save the new game record to the database.
                    gamesRepo.save(game);
                    gamesAdded++;
                    log.debug("Added game '{}' with minimum {} and maximum {} players.", data[0], data[1], data[2]);
                } else {
                    gamesSkipped++;
                    log.debug("Skipped game '{}' because it already exists.", data[0]);
                }
            }

            // Close the file after all game entries have been processed and return true to signify no problems occurred.
            fileReader.close();
        } catch (FileNotFoundException e) {
            log.error("Could not find or open games.txt at src/main/resources/data/games.txt.", e);
            return;
        }

        log.info("Game data initialization completed. Added: {}, skipped: {}, failed: {}.",gamesAdded, gamesSkipped, gamesFailed);

    }
}
