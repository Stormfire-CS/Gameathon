package edu.carroll.cs341.jpa.repo;

import edu.carroll.cs341.jpa.model.Family;
import edu.carroll.cs341.jpa.model.User;
import org.springframework.data.jpa.repository.JpaRepository;

/**
 * Provides database operations for Family entities.
 *
 * <p>This repository extends {@link JpaRepository} to provide standard
 * persistence operations for {@link Family} objects, using {@link Long}
 * as the type of the entity's primary key.</p>
 *
 * <p>It also defines query methods for finding a family by its administrator
 * ID and checking whether a family name already exists, ignoring case.</p>
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author. No code was generated by ChatGPT.</li>
 * </ul>
 */
public interface FamiliesRepository extends JpaRepository<Family, Long> {

    /**
     * Finds a family associated with the specified administrator ID.
     *
     * @param familyAdmin the ID of the family administrator
     * @return the matching family, or {@code null} if no family is found
     */
    Family findByFamilyAdmin(User familyAdmin);

    /**
     * Checks whether a family with the specified name already exists,
     * ignoring differences in letter case.
     *
     * @param familyName the family name to check
     * @return {@code true} if a matching family exists; {@code false} otherwise
     */
    boolean existsByFamilyNameIgnoreCase(String familyName);
}
