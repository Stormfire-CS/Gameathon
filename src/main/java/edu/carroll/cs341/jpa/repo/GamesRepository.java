package edu.carroll.cs341.jpa.repo;

import edu.carroll.cs341.jpa.model.Game;
import edu.carroll.cs341.jpa.model.User;
import org.springframework.data.jpa.repository.JpaRepository;

import java.util.List;

/**
 * Provides database operations for Game entities.
 *
 * <p>This repository extends {@link JpaRepository} to provide standard
 * persistence operations for {@link Game} objects, using {@link Long}
 * as the type of the entity's primary key.</p>
 *
 * <p>It also defines query methods for checking whether a game exists,
 * finding games by name or ID, and retrieving the games visible to a
 * particular user. The visible games include those automatically
 * populated in the database and those added by that specific user.</p>
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author. No code was generated by ChatGPT.</li>
 * </ul>
 */
public interface GamesRepository extends JpaRepository<Game, Long> {

    /**
     * Checks whether a game with the specified name exists.
     *
     * @param gameName the name of the game to check
     * @return {@code true} if a game with that name exists;
     *         {@code false} otherwise
     */
    boolean existsByGameName(String gameName);

    /**
     * Finds a game by its name, ignoring differences in letter case.
     *
     * @param gameName the name of the game to search for
     * @return the matching game, or {@code null} if no match is found
     */
    Game findByGameNameIgnoreCase(String gameName);

    /**
     * Finds a game by its database identifier.
     *
     * @param gameID the ID of the game to search for
     * @return the matching game, or {@code null} if no match is found
     */
    Game findByGameID(Long gameID);

    /**
     * Finds games visible to the specified owner.
     *
     * <p>The results include games automatically populated in the database,
     * which have no associated owner, and games added by the specified owner.
     * The results are ordered alphabetically by game name in ascending order.</p>
     *
     * @param userWhoAdded the user whose added games should
     *                       be included alongside automatically populated games
     * @return a list of automatically populated games and games added by
     *         the specified user, ordered by game name; an empty list
     *         if no matching games are found
     */
    List<Game> findByUserWhoAddedIsNullOrUserWhoAddedOrderByGameNameAsc(User userWhoAdded);
}
