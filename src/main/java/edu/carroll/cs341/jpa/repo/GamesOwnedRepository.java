package edu.carroll.cs341.jpa.repo;

import edu.carroll.cs341.jpa.model.GameOwned;
import edu.carroll.cs341.jpa.model.User;
import org.springframework.data.jpa.repository.JpaRepository;

import java.util.List;

/**
 * Provides database operations for {@link GameOwned} entities.
 *
 * This repository extends {@link JpaRepository} to provide standard
 * persistence operations for {@link GameOwned} objects, using {@link Long}
 * as the type of the entity's primary key.
 *
 * It also defines query methods for retrieving game ownership records
 * by owner ID and game ownership record ID.
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author. No code was generated by ChatGPT.</li>
 * </ul>
 */
public interface GamesOwnedRepository extends JpaRepository<GameOwned, Long> {

    /**
     * Finds all game ownership records associated with the specified owner.
     *
     * @param user the ID of the owner whose games are being retrieved
     * @return a list of game ownership records for the specified owner;
     *         an empty list if no matching records are found
     */
    List<GameOwned> findByUser(User user);

    GameOwned findByGameOwnedID(Long gameOwnedID);
}
