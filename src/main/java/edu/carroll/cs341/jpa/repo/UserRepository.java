package edu.carroll.cs341.jpa.repo;

import edu.carroll.cs341.jpa.model.User;
import org.springframework.data.jpa.repository.JpaRepository;

import java.util.List;

/**
 * Provides database operations for Login entities.
 *
 * <p>This repository extends {@link JpaRepository} to provide standard
 * persistence operations for {@link User} objects, using {@link Long}
 * as the type of the entity's primary key.</p>
 *
 * <p>It also defines a query method for finding user records by username,
 * ignoring differences in letter case. The method returns a list because
 * the application expects either no matching records or a single match.</p>
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author. No code was generated by ChatGPT.</li>
 * </ul>
 */
public interface UserRepository extends JpaRepository<User, Long> {

    /**
     * Finds user records matching the specified username, ignoring
     * differences in letter case.
     *
     * <p>The method returns a list so that no match can be represented
     * by an empty list rather than requiring a single entity result.</p>
     *
     * @param username the username to search for
     * @return a list of matching user records; an empty list if no matches
     *         are found
     */
    List<User> findByUsernameIgnoreCase(String username);


}