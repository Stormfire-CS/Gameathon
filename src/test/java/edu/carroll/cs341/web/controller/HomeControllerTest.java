package edu.carroll.cs341.web.controller;

import edu.carroll.cs341.jpa.model.User;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.resttestclient.autoconfigure.AutoConfigureRestTestClient;
import org.springframework.boot.webmvc.test.autoconfigure.WebMvcTest;
import org.springframework.test.web.servlet.MockMvc;

import static org.hamcrest.Matchers.containsString;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultHandlers.print;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.content;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.redirectedUrl;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

/**
 * Tests the HomeController and its home page endpoint.
 *
 * <p>This test class verifies that the home page is displayed correctly
 * for a logged-in user and that users who are not logged in are redirected
 * to the login page.</p>
 *
 * <p>MockMvc is used to simulate HTTP requests without starting a full web server.
 * This allows the controller's responses and behavior to be tested directly.</p>
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author.
 *   No code was generated by ChatGPT.</li>
 * </ul>
 *
 * @author Max Montowski
 */
@WebMvcTest(HomeController.class)
@AutoConfigureRestTestClient
public class HomeControllerTest {

    /**
     * Performs simulated HTTP requests against the controller and checks the responses.
     */
    @Autowired
    private MockMvc mockMvc;

    /**
     * Tests that the home page loads successfully for a logged-in user.
     *
     * <p>The test verifies that the page returns an HTTP 200 status and displays
     * the expected home page heading and the logged-in user's name.</p>
     *
     * @throws Exception if an error occurs while performing or processing the HTTP request
     */
    @Test
    public void homePageTest() throws Exception {
        // Create a test user to represent someone who is already logged in.
        User user = new User();
        user.setName("Test Player");

        // Request the home page while placing the user in the HTTP session.
        mockMvc.perform(get("/homePage").sessionAttr("loggedInUser", user)).andDo(print())

                // Verify that the page loads successfully.
                .andExpect(status().isOk())

                // Verify that the page displays the expected home page heading.
                .andExpect(content().string(containsString("Gameathon Home")))

                // Verify that the logged-in user's name appears on the page.
                .andExpect(content().string(containsString("Test Player")));
    }

    /**
     * Tests that users who are not logged in cannot access the home page.
     *
     * <p>The test verifies that a request without a logged-in user in the session
     * receives an HTTP redirect to the login page.</p>
     *
     * @throws Exception if an error occurs while performing or processing the HTTP request
     */
    @Test
    public void homePageRequiresLoginTest() throws Exception {
        // Request the home page without providing a logged-in user in the session.
        mockMvc.perform(get("/homePage")).andDo(print())

                // Verify that the request results in an HTTP redirect.
                .andExpect(status().is3xxRedirection())

                // Verify that the user is redirected to the login page.
                .andExpect(redirectedUrl("/login"));
    }
}