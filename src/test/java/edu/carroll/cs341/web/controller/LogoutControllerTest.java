package edu.carroll.cs341.web.controller;

import edu.carroll.cs341.jpa.model.User;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.resttestclient.autoconfigure.AutoConfigureRestTestClient;
import org.springframework.boot.webmvc.test.autoconfigure.WebMvcTest;
import org.springframework.mock.web.MockHttpSession;
import org.springframework.test.web.servlet.MockMvc;

import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultHandlers.print;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.redirectedUrl;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

/**
 * Tests the LogoutController and its logout endpoint.
 *
 * <p>This test class verifies that logging out redirects the user to the login page
 * and invalidates the user's HTTP session.</p>
 *
 * <p>MockMvc is used to simulate HTTP requests without starting a full web server.
 * MockHttpSession is used to create and inspect the user's session during the logout process.</p>
 *
 * <p><b>Sources Used:</b></p>
 * <ul>
 *   <li>ChatGPT – Assisted with generating Javadoc comments for this file
 *   in conjunction with Max Montowski.
 *   All comments were reviewed by the author.
 *   No code was generated by ChatGPT.</li>
 * </ul>
 *
 * @author Max Montowski
 */
@WebMvcTest(LogoutController.class)
@AutoConfigureRestTestClient
public class LogoutControllerTest {

    /**
     * Performs simulated HTTP requests against the controller and checks the responses.
     */
    @Autowired
    private MockMvc mockMvc;

    /**
     * Tests that logging out redirects the user to the login page and invalidates the session.
     *
     * <p>The test creates a session containing a logged-in user, submits a logout request,
     * verifies that the response redirects to the login page, and confirms that the
     * session has been invalidated.</p>
     *
     * @throws Exception if an error occurs while performing or processing the HTTP request
     */
    @Test
    public void logoutTest() throws Exception {
        // Create a mock HTTP session and add a logged-in user.
        MockHttpSession session = new MockHttpSession();
        session.setAttribute("loggedInUser", new User("testuser", "testpassword"));

        // Submit the logout request using the existing session.
        mockMvc.perform(post("/logout").session(session)).andDo(print())

                // Verify that the logout request results in an HTTP redirect.
                .andExpect(status().is3xxRedirection())

                // Verify that the user is redirected to the login page.
                .andExpect(redirectedUrl("/login"));

        // Verify that the logout process invalidated the user's session.
        assertTrue(session.isInvalid(), "Logout should invalidate the session");
    }
}